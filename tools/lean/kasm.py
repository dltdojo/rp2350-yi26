"""A kernel written with labels, assembled into lean/Rv32/Isa.lean's `Instr`s.

A kernel's proof is about a `List Instr` in its Lean file. Written by hand it
would be branch offsets counted on fingers; an experiment's own generator
writes it from labels instead, through this, and puts the result between two
markers in the Lean file, each label's instruction number beside it, so that
the proof names places rather than counting them.

  k = Kernel()
  k.label("LOOP"); k.ins("op", "add", "t0", "t0", "t1"); k.ins("br", "bne", "t0", "zero", "LOOP")
  labels, texts = k.assemble()       # {name: instruction number}, [".op .add 5 5 6", …]
  new = splice(text, block, "kernel.py")

Instruction kinds and their arguments, registers by ABI name:

  op    op rd rs1 rs2          opi  op rd rs1 imm         sh  op rd rs1 shamt
  ld    op rd rs1 off          st   op rs1 rs2 off        br  op rs1 rs2 label
  jal   rd label               jalr rd rs1 off            auipc rd imm   lui rd imm
  ecall

From exp228's kernel.py, the second kernel to need it being exp229's.
"""
import re

REG = dict(zero=0, ra=1, sp=2, gp=3, tp=4, t0=5, t1=6, t2=7, s0=8, s1=9, a0=10, a1=11, a2=12, a3=13,
           a4=14, a5=15, a6=16, a7=17, s2=18, s3=19, s4=20, s5=21, s6=22, s7=23, s8=24, s9=25,
           s10=26, s11=27, t3=28, t4=29, t5=30, t6=31)


class Kernel:
    def __init__(self):
        self.items = []     # ("label", name) | ("i", kind, args)

    def label(self, name):
        self.items.append(("label", name))

    def ins(self, kind, *args):
        self.items.append(("i", kind, args))

    def assemble(self):
        """Every label's instruction number, and each instruction as Lean writes it."""
        labels, n = {}, 0
        for it in self.items:
            if it[0] == "label":
                assert it[1] not in labels, it[1]
                labels[it[1]] = n
            else:
                n += 1
        out, pc = [], 0
        for it in self.items:
            if it[0] == "label":
                continue
            out.append(lean_instr(it[1], it[2], labels, pc))
            pc += 1
        return labels, out


def lean_instr(kind, args, labels, pc):
    r = lambda x: REG[x]   # noqa: E731
    if kind == "opi":
        op, rd, rs, v = args
        return f".opi .{op} {r(rd)} {r(rs)} {v & 0xfff:#x}"
    if kind == "op":
        op, rd, a, b = args
        return f".op .{op} {r(rd)} {r(a)} {r(b)}"
    if kind == "sh":
        op, rd, rs, v = args
        return f".sh .{op} {r(rd)} {r(rs)} {v}"
    if kind == "ld":
        op, rd, rs, v = args
        assert -2048 <= v < 2048
        return f".ld .{op} {r(rd)} {r(rs)} {v & 0xfff:#x}"
    if kind == "st":
        op, rs1, rs2, v = args
        assert -2048 <= v < 2048
        return f".st .{op} {r(rs1)} {r(rs2)} {v & 0xfff:#x}"
    if kind == "br":
        op, a, b, lbl = args
        off = 4 * (labels[lbl] - pc)
        assert -4096 <= off < 4096, (lbl, off)
        return f".br .{op} {r(a)} {r(b)} {(off >> 1) & 0xfff:#x}"
    if kind == "jal":
        rd, lbl = args
        off = 4 * (labels[lbl] - pc)
        return f".jal {r(rd)} {(off >> 1) & 0xfffff:#x}"
    if kind == "jalr":
        rd, rs, v = args
        return f".jalr {r(rd)} {r(rs)} {v & 0xfff:#x}"
    if kind == "auipc":
        rd, v = args
        return f".auipc {r(rd)} {v:#x}"
    if kind == "lui":
        rd, v = args
        return f".lui {r(rd)} {v:#x}"
    if kind == "ecall":
        return ".ecall"
    raise ValueError(kind)


def splice(text, block, who):
    """Put block between `-- BEGIN generated by WHO` and `-- END generated by WHO` in text."""
    pat = re.compile(r"-- BEGIN generated by " + re.escape(who) + r".*?-- END generated by " + re.escape(who), re.S)
    assert pat.search(text), f"no block generated by {who}"
    return pat.sub(lambda _: block, text)
