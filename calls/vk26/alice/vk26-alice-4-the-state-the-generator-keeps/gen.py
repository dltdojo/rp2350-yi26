"""vk26-alice-4 — what the shell compiles in, computed here.

  gen.py OUT.h RV32RUN

  KERNEL, KERNEL_SHA   kernel.bin, as proof/Drbg.lean writes it, checked
                       against kernel.sha256
  CASES                every NIST case of cavp/Hash_DRBG_SHA256.txt: V and C
                       as drbg.py instantiates them, NIST's ReturnedBits, and
                       the SHA-256 of the region's first WINDOW bytes after the
                       second Generate, as drbg.py says the kernel leaves them
  M, INTERVAL          4 blocks a Generate (NIST's 1024 bits); the interval 2,
                       so that the counter, starting at 1, is allowed twice and
                       the third run must halt with 1, reseed required
  INSTRET_GEN, INSTRET_RESEED
                       minstret for a Generate and for the reseed check, as
                       the Hazard3 RTL counts them under tools/hazard3/harness

Before writing anything, the first case on the Lean model and the RTL: both
Generates halt with 0, the model after exactly COST(M) instructions, the
third with 1 after 7, each region drbg.py's; and the RTL's minstret the same
for three cases.
"""
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "..", "tools", "hazard3", "shell"))
sys.path.insert(0, os.path.join(HERE, "..", "tools"))
from expect import c_bytes, kernel_bin, model  # noqa: E402
from region import rtl_region  # noqa: E402
from drbg import OUT, cavp_cases, drbg_generate, drbg_image, drbg_instantiate, drbg_region  # noqa: E402

M, INTERVAL = 4, 2
# The region's bytes a Generate can write lie below it; past it, zeros.
WINDOW = 0x700
# proof/Drbg.lean's COST, and reseed_run's 7.
COST = 2030 + 566 * M
RESEED = 7


def three_runs(kernel, case):
    """drbg.py's (halt code, region) for a case's three runs: two Generates, then the reseed check."""
    state = drbg_instantiate(case["entropy"], case["nonce"], case["pers"])
    img = drbg_image(kernel, state, INTERVAL, M)
    out = []
    for _ in range(3):
        code, region = drbg_region(img, state, INTERVAL, M)
        out.append((code, region))
        made = drbg_generate(state, 32 * M, INTERVAL)
        if made:
            state = made[1]
        img = region
    return out


def case_runs(rv32run, kernel, case, where):
    """The three runs on `where` ("model" or "rtl"), each from the region the last left: [(outcome line, region)]."""
    runs = []
    state = drbg_instantiate(case["entropy"], case["nonce"], case["pers"])
    img = drbg_image(kernel, state, INTERVAL, M)
    for _ in range(3):
        ran, region = model(rv32run, img, COST + 10) if where == "model" else rtl_region(img, 5000000)
        runs.append((ran, region))
        img = region
    return runs


def write_drbg_expect(out, rv32run):
    kernel, sha = kernel_bin(os.path.join(HERE, "kernel"))
    cases = cavp_cases()
    want0 = three_runs(kernel, cases[0])
    for (ran, region), (code, region0), fuel in zip(case_runs(rv32run, kernel, cases[0], "model"), want0,
                                                   (COST, COST, RESEED)):
        if ran != f"halt code={code:08x} count={fuel}" or region != region0:
            sys.exit(f"gen.py: {cases[0]['name']}: the model {ran}, its region {'' if region == region0 else 'not '}"
                     "drbg.py's")
    gen, reseed = set(), set()
    for case in cases[:3]:
        for (ran, region), (code, region0) in zip(case_runs(rv32run, kernel, case, "rtl"), three_runs(kernel, case)):
            said = ran.split()
            if said[:2] != ["halt", f"code={code:08x}"] or region != region0:
                sys.exit(f"gen.py: {case['name']}: the RTL said {ran}")
            (gen if code == 0 else reseed).add(int(said[2].split("=")[1]))
    if len(gen) != 1 or len(reseed) != 1:
        sys.exit(f"gen.py: the RTL counted {sorted(gen)} for a Generate and {sorted(reseed)} for the reseed check")
    gen, reseed = gen.pop(), reseed.pop()
    with open(out, "w") as f:
        f.write("// Generated by vk26-alice-4/gen.py. Do not edit.\n#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define KERNEL_LEN {len(kernel)}\n#define NCASES {len(cases)}\n#define M {M}\n"
                f"#define INTERVAL {INTERVAL}\n#define WINDOW 0x{WINDOW:x}u\n")
        f.write(f"#define INSTRET_GEN {gen}u\n#define INSTRET_RESEED {reseed}u\n")
        f.write("static const uint8_t KERNEL[KERNEL_LEN] = {" + c_bytes(kernel) + "};\n")
        f.write("static const uint8_t KERNEL_SHA[32] = {" + c_bytes(bytes.fromhex(sha)) + "};\n")
        f.write("struct kcase { char name[16]; uint8_t v[55], c[55], want[32 * M], after[32]; };\n")
        f.write("static const struct kcase CASES[NCASES] = {\n")
        for case in cases:
            v, c, _ = drbg_instantiate(case["entropy"], case["nonce"], case["pers"])
            after = three_runs(kernel, case)[1][1]
            if after[OUT:OUT + 32 * M] != case["want"] or any(after[WINDOW:]):
                sys.exit(f"gen.py: {case['name']}: drbg.py's second Generate is not NIST's")
            f.write(f'    {{"{case["name"]}", {{{c_bytes(v)}}}, {{{c_bytes(c)}}}, {{{c_bytes(case["want"])}}}, '
                    f'{{{c_bytes(hashlib.sha256(after[:WINDOW]).digest())}}}}},\n')
        f.write("};\n")
    print(f"{out}: kernel {sha[:16]}…, {len(cases)} NIST cases, RTL minstret a Generate {gen}, the reseed "
          f"check {reseed}: the proof's {COST} and {RESEED}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    write_drbg_expect(sys.argv[1], sys.argv[2])
