"""vk26-alice-3 — what the shell compiles in, computed here.

  gen.py OUT.h RV32RUN

  KERNEL, KERNEL_SHA   kernel.bin, as proof/Count.lean writes it, checked
                       against kernel.sha256
  FIXED                the streams the shell runs after the TRNG's two, each
                       4096 samples as 1024 words (sample i is byte i % 4 of
                       word i / 4), with count.py's largest count for it
  INSTRET              minstret for a run, as the Hazard3 RTL counts it under
                       tools/hazard3/harness: by `from_boot` the same for
                       every input, so one number

Before writing anything, every fixed stream on the Lean model and the RTL:
both must halt with 0, the model after exactly COST instructions and with
count.py's histogram, the RTL with the same minstret every time.
"""
import os
import struct
import sys
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "..", "tools", "hazard3", "shell"))
sys.path.insert(0, os.path.join(HERE, "..", "tools"))
from expect import c_bytes, kernel_bin, model  # noqa: E402
from region import rtl_region  # noqa: E402
from count import L, count_image, count_outcome, count_streams, histogram  # noqa: E402

# After the TRNG's two, by name in count.count_streams().
FIXED = ["each value 16 times", "0xa5 at 1000 places", "bits 1 three times in four"]
WORDS = L // 4
# proof/Count.lean's COST.
COST = 8 + 256 * (2 + 6 * L + 9) + 4


def count_run(rv32run, kernel, name, samples):
    """The model and the RTL on one image: the RTL's minstret."""
    img = count_image(kernel, samples)
    ran, region = model(rv32run, img, COST + 10)
    if ran != f"halt code=00000000 count={COST}":
        sys.exit(f"gen.py: {name}: the model {ran}")
    for at, b in count_outcome(samples).items():
        if region[at:at + len(b)] != b:
            sys.exit(f"gen.py: {name}: the model's bytes at {at:#x} are not count.py's")
    said = rtl_region(img, 20000000)[0].split()
    if said[:2] != ["halt", "code=00000000"]:
        sys.exit(f"gen.py: {name}: the RTL said {' '.join(said)}")
    return int(said[2].split("=")[1])


def write_count_expect(out, rv32run):
    kernel, sha = kernel_bin(os.path.join(HERE, "kernel"))
    every = count_streams()
    with ThreadPoolExecutor(len(FIXED)) as pool:
        counts = list(pool.map(lambda n: count_run(rv32run, kernel, n, every[n]), FIXED))
    if len(set(counts)) != 1:
        sys.exit(f"gen.py: the RTL counted {counts} for the fixed streams, not one number")
    with open(out, "w") as f:
        f.write("// Generated by vk26-alice-3/gen.py. Do not edit.\n#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define KERNEL_LEN {len(kernel)}\n#define NFIXED {len(FIXED)}\n#define WORDS {WORDS}\n")
        f.write(f"#define INSTRET {counts[0]}u\n")
        f.write("static const uint8_t KERNEL[KERNEL_LEN] = {" + c_bytes(kernel) + "};\n")
        f.write("static const uint8_t KERNEL_SHA[32] = {" + c_bytes(bytes.fromhex(sha)) + "};\n")
        f.write("struct fixed { const char *name; uint32_t most; uint32_t words[WORDS]; };\n")
        f.write("static const struct fixed FIXED[NFIXED] = {\n")
        for name in FIXED:
            words = struct.unpack(f"<{WORDS}I", bytes(every[name]))
            f.write(f'    {{"{name}", {max(histogram(every[name]))}, {{'
                    + ", ".join(f"0x{w:08x}" for w in words) + "}},\n")
        f.write("};\n")
    print(f"{out}: kernel {sha[:16]}…, {len(FIXED)} fixed streams, RTL minstret {counts[0]}: the proof's {COST}, "
          f"{counts[0] - COST} more")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    write_count_expect(sys.argv[1], sys.argv[2])
