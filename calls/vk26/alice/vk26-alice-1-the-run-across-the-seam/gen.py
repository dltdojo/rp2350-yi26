"""vk26-alice-1 — what the shell compiles in, computed here.

  gen.py OUT.h RV32RUN

  KERNEL, KERNEL_SHA   kernel.bin, as proof/Seam.lean writes it, checked
                       against kernel.sha256
  FIXED                the streams the shell runs after the TRNG's, each
                       4096 samples packed 32 to a word (sample i is bit i % 32
                       of word i / 32): seam.py's, with the halt code seam.py
                       gives each and hashlib's SHA-256 of each window that
                       passed
  INSTRET              minstret for each halt code 0 to 4, as the Hazard3 RTL
                       counts it under tools/hazard3/harness. By `from_boot`
                       the count depends on where the kernel stops and nothing
                       else, so one stream for each code is the count for
                       every stream that stops there, the TRNG's included

Before writing anything, every fixed stream on the Lean model and the RTL:
both must halt with seam.py's code, the model after exactly the count
`from_boot` proves, its digests hashlib's.
"""
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "..", "tools", "hazard3", "shell"))
from expect import c_bytes, kernel_bin, model, rtl  # noqa: E402
from seam import DIGESTS, N, WINDOWS, image, seam_outcome, streams  # noqa: E402
from health import pack  # noqa: E402  (seam.py has put alice/tools on the path)

# The order the shell runs them in, after the TRNG's own: the seam caught and
# its control, then each remaining code once.
FIXED = ["seam 11+10", "seam 10+10", "stuck at 1, window 1", "21 alike in window 3",
         "nine ones then a zero, window 4"]
WORDS = N * WINDOWS // 32


def cost(code):
    """proof/Seam.lean's `cost (stop …)`, by the halt code."""
    return 69699 if code == 0 else 17431 + 17421 * (code - 1)



def write_seam_expect(out, rv32run):
    kernel, sha = kernel_bin(os.path.join(HERE, "kernel"))
    every = streams()
    rows, instret = [], {}
    for name in FIXED:
        words = every[name]
        if any(w not in (0, 1) for w in words):
            sys.exit(f"gen.py: {name}: a sample word is not 0 or 1, and the shell writes only 0 or 1")
        code, digests, _ = seam_outcome(words)
        img = image(kernel, words)
        ran, region = model(rv32run, img, 100000)
        if ran != f"halt code={code:08x} count={cost(code)}":
            sys.exit(f"gen.py: {name}: seam.py says {code} after {cost(code)}, the model {ran}")
        for w, d in enumerate(digests):
            if region[DIGESTS + 32 * w:DIGESTS + 32 * w + 32] != d:
                sys.exit(f"gen.py: {name}: the model's digest {w} is not hashlib's")
        said = rtl(img).split()
        if said[:2] != ["halt", f"code={code:08x}"]:
            sys.exit(f"gen.py: {name}: the RTL said {' '.join(said)}")
        n = int(said[2].split("=")[1])
        if instret.setdefault(code, n) != n:
            sys.exit(f"gen.py: {name}: the RTL counted {n} for code {code}, and {instret[code]} before")
        rows.append((name, pack(words), code, digests))
    if sorted(instret) != list(range(WINDOWS + 1)):
        sys.exit(f"gen.py: the fixed streams halt with {sorted(instret)}, not every code 0 to 4")
    with open(out, "w") as f:
        f.write("// Generated by vk26-alice-1/gen.py. Do not edit.\n#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define KERNEL_LEN {len(kernel)}\n#define NFIXED {len(rows)}\n#define WORDS {WORDS}\n")
        f.write("static const uint8_t KERNEL[KERNEL_LEN] = {" + c_bytes(kernel) + "};\n")
        f.write("static const uint8_t KERNEL_SHA[32] = {" + c_bytes(bytes.fromhex(sha)) + "};\n")
        f.write("static const uint32_t INSTRET[5] = {" + ", ".join(str(instret[c]) for c in range(5)) + "};\n")
        f.write("struct fixed { const char *name; uint32_t want; uint32_t bits[WORDS]; uint8_t digest[4][32]; };\n")
        f.write("static const struct fixed FIXED[NFIXED] = {\n")
        for name, bits, code, digests in rows:
            ds = ", ".join("{" + c_bytes(d) + "}" for d in digests) or "{0}"
            f.write(f'    {{"{name}", {code}, {{' + ", ".join(f"0x{b:08x}" for b in bits) + f"}}, {{{ds}}}}},\n")
        f.write("};\n")
    print(f"{out}: kernel {sha[:16]}…, {len(rows)} fixed streams, RTL minstret "
          + " ".join(f"{c}:{instret[c]}" for c in range(5)))
    for c in range(5):
        print(f"  code {c}: the proof's count {cost(c)}, the RTL's minstret {instret[c]}, "
              f"{instret[c] - cost(c)} more ({4 if c == 0 else c - 1} HASH calls)")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    write_seam_expect(sys.argv[1], sys.argv[2])
