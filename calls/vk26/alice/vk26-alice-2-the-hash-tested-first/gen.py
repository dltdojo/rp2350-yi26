"""vk26-alice-2 — what the shell compiles in, computed here.

  gen.py OUT.h RV32RUN

  KERNEL, KERNEL_SHA   kernel.bin, as proof/Trust.lean writes it, checked
                       against kernel.sha256
  KAT_MSG, KAT_WANT    the KAT's 64-byte message and hashlib's SHA-256 of it:
                       what the shell puts in the image for the kernel to ask
                       HASH about, and what HASH must answer
  FIXED                the streams the shell runs after the TRNG's, each 2048
                       samples packed 32 to a word (sample i is bit i % 32 of
                       word i / 32), whether the shell spoils HASH's answer to
                       the KAT for it, the halt code trust.py gives, and
                       hashlib's SHA-256 of window 1 when that code is 0
  INSTRET              minstret for each halt code 0 to 3, as the Hazard3 RTL
                       counts it under tools/hazard3/harness. By `from_boot`
                       the count depends on the code alone. Code 2's comes
                       from an image whose expected digest is wrong, which
                       takes the kernel down the same path as a wrong answer

Before writing anything, every fixed stream on the Lean model and the RTL:
both must halt with trust.py's code, the model after exactly the count
`from_boot` proves, its writes trust.py's.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "..", "tools", "hazard3", "shell"))
sys.path.insert(0, os.path.join(HERE, "..", "tools"))
from expect import c_bytes, kernel_bin, model  # noqa: E402
from region import rtl_region  # noqa: E402
from trust import KAT, OUTPUT, WINDOWS, bad_wants, image, kat_want, trust_outcome, trust_streams  # noqa: E402
from health import N, pack  # noqa: E402

# After the TRNG's: (name in trust.trust_streams(), the shell spoils the KAT's answer).
FIXED = [("fair", True), ("seam 11+10", False), ("seam 10+10", False), ("stuck at 1 from the start", False)]
WORDS = N * WINDOWS // 32
# proof/Trust.lean's cost, by the halt code.
COST = {2: 43, 1: 17462, 3: 34878, 0: 34885}



def check_run(rv32run, name, words, want):
    """The model and the RTL on one image: (code, the RTL's minstret)."""
    kernel = open(os.path.join(HERE, "kernel.bin"), "rb").read()
    code, writes, _ = trust_outcome(words, want)
    img = image(kernel, words, want)
    ran, region = model(rv32run, img, 100000)
    if ran != f"halt code={code:08x} count={COST[code]}":
        sys.exit(f"gen.py: {name}: trust.py says {code} after {COST[code]}, the model {ran}")
    for at, b in writes.items():
        if region[at:at + len(b)] != b:
            sys.exit(f"gen.py: {name}: the model's bytes at {at:#x} are not trust.py's")
    said = rtl_region(img)[0].split()
    if said[:2] != ["halt", f"code={code:08x}"]:
        sys.exit(f"gen.py: {name}: the RTL said {' '.join(said)}")
    return code, int(said[2].split("=")[1])


def write_trust_expect(out, rv32run):
    kernel, sha = kernel_bin(os.path.join(HERE, "kernel"))
    every = trust_streams()
    rows, instret = [], {}
    cases = [(n, every[n], None) for n, _ in FIXED] + [("a wrong expected digest", every["fair"],
                                                         bad_wants()["first bit flipped"])]
    for name, words, want in cases:
        if any(w not in (0, 1) for w in words):
            sys.exit(f"gen.py: {name}: a sample word is not 0 or 1, and the shell writes only 0 or 1")
        code, n = check_run(rv32run, name, words, want)
        if instret.setdefault(code, n) != n:
            sys.exit(f"gen.py: {name}: the RTL counted {n} for code {code}, and {instret[code]} before")
    if sorted(instret) != [0, 1, 2, 3]:
        sys.exit(f"gen.py: the cases halt with {sorted(instret)}, not every code 0 to 3")
    for name, spoil in FIXED:
        words = every[name]
        # A spoiled answer is a failed KAT, whatever the samples: code 2.
        code, writes, _ = trust_outcome(words, None if not spoil else bad_wants()["first bit flipped"])
        digest = writes.get(OUTPUT, bytes(32))
        rows.append((name, int(spoil), code, pack(words), digest))
    with open(out, "w") as f:
        f.write("// Generated by vk26-alice-2/gen.py. Do not edit.\n#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define KERNEL_LEN {len(kernel)}\n#define NFIXED {len(rows)}\n#define WORDS {WORDS}\n")
        f.write("static const uint8_t KERNEL[KERNEL_LEN] = {" + c_bytes(kernel) + "};\n")
        f.write("static const uint8_t KERNEL_SHA[32] = {" + c_bytes(bytes.fromhex(sha)) + "};\n")
        f.write("static const uint8_t KAT_MSG[64] = {" + c_bytes(KAT) + "};\n")
        f.write("static const uint8_t KAT_WANT[32] = {" + c_bytes(kat_want()) + "};\n")
        f.write("static const uint32_t INSTRET[4] = {" + ", ".join(str(instret[c]) for c in range(4)) + "};\n")
        f.write("struct fixed { const char *name; uint32_t spoil; uint32_t want; uint32_t bits[WORDS]; "
                "uint8_t digest[32]; };\n")
        f.write("static const struct fixed FIXED[NFIXED] = {\n")
        for name, spoil, code, bits, digest in rows:
            f.write(f'    {{"{name}", {spoil}, {code}, {{' + ", ".join(f"0x{b:08x}" for b in bits)
                    + f"}}, {{{c_bytes(digest)}}}}},\n")
        f.write("};\n")
    print(f"{out}: kernel {sha[:16]}…, {len(rows)} fixed streams, RTL minstret "
          + " ".join(f"{c}:{instret[c]}" for c in range(4)))
    for c in range(4):
        calls = 2 if c == 0 else 1
        print(f"  code {c}: the proof's count {COST[c]}, the RTL's minstret {instret[c]}, "
              f"{instret[c] - COST[c]} more ({calls} HASH call{'s' if calls > 1 else ''})")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    write_trust_expect(sys.argv[1], sys.argv[2])
