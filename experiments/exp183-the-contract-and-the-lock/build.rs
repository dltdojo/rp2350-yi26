use std::{env, fs, path::PathBuf};

fn flag(name: &str, default: bool) -> bool {
    match env::var(name) {
        Ok(v) => matches!(v.as_str(), "on" | "1" | "true" | "yes"),
        Err(_) => default,
    }
}

fn main() {
    let backend = env::var("EXP183_BACKEND").unwrap_or_else(|_| "test_key".to_string());
    match backend.as_str() {
        "test_key" | "bank8" | "puf" | "otp_sim" => {}
        other => panic!("EXP183_BACKEND must be `test_key`, `bank8`, `puf`, or `otp_sim`, not `{other}`"),
    };

    let up = env::var("EXP183_UP").unwrap_or_else(|_| "none".to_string());
    let waits = match up.as_str() {
        "none" => false,
        "button" => true,
        other => panic!("EXP183_UP must be `none` or `button`, not `{other}`"),
    };

    let keepalive = flag("EXP183_KEEPALIVE", true);
    let hold: u64 = env::var("EXP183_HOLD_MS").ok().and_then(|v| v.parse().ok()).unwrap_or(0);
    let timeout: u64 = env::var("EXP183_TIMEOUT_MS").ok().and_then(|v| v.parse().ok()).unwrap_or(10_000);

    let out = PathBuf::from(env::var_os("OUT_DIR").unwrap());
    fs::write(
        out.join("exp183_config.rs"),
        format!(
            "// generated by build.rs — do not edit\n\
             pub const ACTIVE_BACKEND: &str = {backend:?};\n\
             pub const UP_MODE: &str = {up:?};\n\
             pub const WAIT_FOR_USER: bool = {waits};\n\
             pub const KEEPALIVE: bool = {keepalive};\n\
             pub const HOLD_MS: u64 = {hold};\n\
             pub const TIMEOUT_MS: u64 = {timeout};\n"
        ),
    )
    .unwrap();

    for var in ["EXP183_BACKEND", "EXP183_UP", "EXP183_KEEPALIVE", "EXP183_HOLD_MS", "EXP183_TIMEOUT_MS"] {
        println!("cargo:rerun-if-env-changed={var}");
    }
    println!("cargo:rerun-if-changed=build.rs");
}
