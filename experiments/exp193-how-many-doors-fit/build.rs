// How many doors this build opens. The wall is found by walking towards it, so
// the number of interfaces is a build input and `drop.sh` increments it until
// the board stops enumerating.

use std::{env, fs, path::PathBuf};

/// Above this the walk is not measuring a descriptor budget any more, it is
/// measuring how many `State`s were preallocated. Kept in step with `MAX_HID`
/// in `src/main.rs`, and asserted there.
const CEILING: u32 = 12;

fn main() {
    let raw = env::var("EXP193_HID").unwrap_or_else(|_| "0".to_string());
    let hid: u32 = raw
        .parse()
        .unwrap_or_else(|_| panic!("EXP193_HID must be a number 0..={CEILING}, not `{raw}`"));
    assert!(
        hid <= CEILING,
        "EXP193_HID must be 0..={CEILING}, not {hid} — see MAX_HID in src/main.rs"
    );

    // Which lane. `embassy-usb`'s interface list is a `heapless::Vec` whose
    // capacity is a compile-time setting defaulting to 4, so the number below
    // is not a description of this firmware — it is the ceiling the USB stack
    // was compiled with, and the firmware logs it because the first wall this
    // experiment hit was that number and not a byte count.
    let wide = env::var_os("CARGO_FEATURE_WIDE").is_some();
    let budget = if wide { 8 } else { 4 };

    let out = PathBuf::from(env::var_os("OUT_DIR").unwrap());
    fs::write(
        out.join("exp193_config.rs"),
        format!(
            "// generated by build.rs — do not edit\n\
             pub const HID: usize = {hid};\n\
             pub const LANE: &str = {lane:?};\n\
             pub const INTERFACE_BUDGET: usize = {budget};\n",
            lane = if wide { "wide" } else { "narrow" },
        ),
    )
    .unwrap();
    println!("cargo:rerun-if-env-changed=EXP193_HID");
    println!("cargo:rerun-if-changed=build.rs");
}
