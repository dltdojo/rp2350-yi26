// One source, two claims. `authenticatorGetInfo`'s `versions` field is a list
// of the CTAP versions an authenticator supports, and this device supports part
// of one — which the field has no way to say. So which claim it makes is a
// build input and the experiment measures both, rather than one being chosen
// here and defended in prose.
use std::{env, fs, path::PathBuf};

fn main() {
    // "fido2" claims FIDO_2_0, which is an overclaim. "none" claims nothing,
    // which is structurally valid and may be useless. Default is the honest
    // one, so a plain `cargo build` does not ship the lie.
    let claim = env::var("EXP169_CLAIM").unwrap_or_else(|_| "none".to_string());
    let versions: &[&str] = match claim.as_str() {
        "fido2" => &["FIDO_2_0"],
        "none" => &[],
        other => panic!("EXP169_CLAIM must be `none` or `fido2`, not `{other}`"),
    };
    let list = versions
        .iter()
        .map(|v| format!("{v:?}"))
        .collect::<Vec<_>>()
        .join(", ");
    let out = PathBuf::from(env::var_os("OUT_DIR").unwrap());
    fs::write(
        out.join("exp169_config.rs"),
        format!(
            "// generated by build.rs — do not edit\n\
             pub const CLAIM: &str = {claim:?};\n\
             /// What goes in getInfo's `versions`, which is key 0x01.\n\
             pub const VERSIONS: [&str; {}] = [{list}];\n",
            versions.len()
        ),
    )
    .unwrap();
    println!("cargo:rerun-if-env-changed=EXP169_CLAIM");
    println!("cargo:rerun-if-changed=build.rs");
}
