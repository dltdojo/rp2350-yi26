use std::{env, fs, path::PathBuf};

fn flag(name: &str, default: bool) -> bool {
    match env::var(name) {
        Ok(v) => matches!(v.as_str(), "on" | "1" | "true" | "yes"),
        Err(_) => default,
    }
}

fn main() {
    let up = env::var("EXP188_UP").unwrap_or_else(|_| "button".to_string());
    let waits = match up.as_str() {
        "none" => false,
        "button" => true,
        other => panic!("EXP188_UP must be `none` or `button`, not `{other}`"),
    };
    let keepalive = flag("EXP188_KEEPALIVE", true);
    let hold: u64 = env::var("EXP188_HOLD_MS").ok().and_then(|v| v.parse().ok()).unwrap_or(0);
    let timeout: u64 = env::var("EXP188_TIMEOUT_MS").ok().and_then(|v| v.parse().ok()).unwrap_or(60_000);
    let reset_window: u64 = env::var("EXP188_RESET_WINDOW_SECS").ok().and_then(|v| v.parse().ok()).unwrap_or(10);
    let max_rk: usize = env::var("EXP188_MAX_RK").ok().and_then(|v| v.parse().ok()).unwrap_or(16);

    let out = PathBuf::from(env::var_os("OUT_DIR").unwrap());
    fs::write(
        out.join("exp188_config.rs"),
        format!(
            "// generated by build.rs — do not edit\n\
             pub const UP_MODE: &str = {up:?};\n\
             /// Does this build wait for a person before making a credential?\n\
             pub const WAIT_FOR_USER: bool = {waits};\n\
             /// Does it say \"still here\" while it waits?\n\
             pub const KEEPALIVE: bool = {keepalive};\n\
             /// Refuse to answer before this many ms, even with the button held.\n\
             pub const HOLD_MS: u64 = {hold};\n\
             /// How long a person who is not there has, in ms.\n\
             pub const TIMEOUT_MS: u64 = {timeout};\n\
             /// Seconds after boot during which authenticatorReset (0x07) is permitted.\n\
             pub const RESET_WINDOW_SECS: u64 = {reset_window};\n\
             /// Maximum number of discoverable resident credentials stored on device.\n\
             pub const MAX_RESIDENT_KEYS: usize = {max_rk};\n"
        ),
    )
    .unwrap();
    for var in ["EXP188_UP", "EXP188_KEEPALIVE", "EXP188_HOLD_MS", "EXP188_TIMEOUT_MS", "EXP188_RESET_WINDOW_SECS", "EXP188_MAX_RK"] {
        println!("cargo:rerun-if-env-changed={var}");
    }
    println!("cargo:rerun-if-changed=build.rs");
}

