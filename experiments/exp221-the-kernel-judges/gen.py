"""exp221 — what the shell checks against, computed here and compiled in.

  gen.py OUT.h RV32RUN

  KERNEL, KERNEL_SHA    kernel.bin, as proof/Same.lean writes it, checked
                        against kernel.sha256
  INVERT, REVERSE       the two PIO programs' words, out of exp220's
                        `words_invert` and `words_reverse`
  WORDS                 the message, as 16 little-endian words: what goes
                        into the blocks
  INVERTED, REVERSED    each complemented, and each reversed: what each
                        block alone must give back
  EXPECT_INSTRET        the Hazard3 RTL's minstret for the kernel judging two
                        equal lists, the ones both orders should give

and, before writing anything, the Lean model run on the same image (it must
halt with 0 after exactly 73, the proved count) and on one where a single bit
of the second list differs (it must halt with 1, after 73 too).
"""
import hashlib
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
THROUGH = os.path.join(HERE, "..", "exp220-either-order", "proof", "Through.lean")
sys.path.insert(0, os.path.join(HERE, "..", "..", "tools", "hazard3", "shell"))
from expect import c_bytes, kernel_bin, model, rtl  # noqa: E402

MESSAGE = b"exp221: PIO0 and PIO1 answer, and a proved RV32IM kernel judges."
FIRST, SECOND = 0x1000, 0x2000


def theorem_words(name, o):
    m = re.search(rf"^theorem {name} : prog \.{o} = \[([^\]]*)\]", open(THROUGH).read(), re.M)
    if not m:
        sys.exit(f"gen.py: no {name} in exp220's Through.lean")
    return [int(t, 16) for t in m[1].split(",")]


def bit_reverse(w):
    return int(f"{w:032b}"[::-1], 2)


def judged(kernel, a, b):
    img = bytearray(SECOND + 64)
    img[:len(kernel)] = kernel
    img[FIRST:FIRST + 64] = struct.pack("<16I", *a)
    img[SECOND:SECOND + 64] = struct.pack("<16I", *b)
    return bytes(img)


def write_judge(out, rv32run):
    if len(MESSAGE) != 64:
        sys.exit("gen.py: the message must be 64 bytes")
    kernel, sha = kernel_bin(os.path.join(HERE, "kernel"))
    words = struct.unpack("<16I", MESSAGE)
    both = [~bit_reverse(w) & 0xffffffff for w in words]
    ran, _ = model(rv32run, judged(kernel, both, both), 1000)
    if ran != "halt code=00000000 count=73":
        sys.exit(f"gen.py: on two equal lists the model did not halt with 0 after 73: {ran}")
    other = list(both)
    other[5] ^= 1 << 17
    ran, _ = model(rv32run, judged(kernel, both, other), 1000)
    if ran != "halt code=00000001 count=73":
        sys.exit(f"gen.py: on lists one bit apart the model did not halt with 1 after 73: {ran}")
    ran = rtl(judged(kernel, both, both))
    if not ran.startswith("halt code=00000000 instret="):
        sys.exit(f"gen.py: the RTL did not halt with 0: {ran}")
    instret = int(ran.split("instret=")[1].split()[0])
    invert, reverse = theorem_words("words_invert", "invert"), theorem_words("words_reverse", "reverse")
    u32 = lambda ws: ", ".join(f"0x{w:08x}u" for w in ws)
    u16 = lambda ws: ", ".join(f"0x{w:04x}" for w in ws)
    with open(out, "w") as f:
        f.write("// Generated by exp221/gen.py. Do not edit.\n#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define KERNEL_LEN {len(kernel)}\n#define FIRST_OFF {FIRST:#x}\n#define SECOND_OFF {SECOND:#x}\n")
        f.write(f"#define EXPECT_INSTRET {instret}u   // the RTL harness's minstret for this kernel\n")
        f.write("static const uint8_t KERNEL[KERNEL_LEN] = {" + c_bytes(kernel) + "};\n")
        f.write("static const uint8_t KERNEL_SHA[32] = {" + c_bytes(bytes.fromhex(sha)) + "};\n\n")
        f.write(f"// words_invert: {' '.join(f'{w:04x}' for w in invert)}   (PIO0)\n")
        f.write(f"// words_reverse: {' '.join(f'{w:04x}' for w in reverse)}   (PIO1)\n")
        f.write(f"#define PROGRAM_LEN 3\nstatic const uint16_t INVERT[3] = {{{u16(invert)}}};\n")
        f.write(f"static const uint16_t REVERSE[3] = {{{u16(reverse)}}};\n#define JMP_0 0x0000u\n\n")
        f.write(f"// {MESSAGE.decode()}\n")
        f.write(f"static const uint32_t WORDS[16] = {{{u32(words)}}};\n")
        f.write(f"static const uint32_t INVERTED[16] = {{{u32([~w & 0xffffffff for w in words])}}};\n")
        f.write(f"static const uint32_t REVERSED[16] = {{{u32([bit_reverse(w) for w in words])}}};\n")
    print(f"{out}: kernel {sha[:16]}…, RTL minstret {instret}, model 73 both ways")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    write_judge(sys.argv[1], sys.argv[2])
