"""
Writes proof/Box.lean.

Three proofs as their own check.sh holds them -- read here, not written again -- each with its `#print` lines and
what follows them dropped: exp240's proof/Wx.lean (namespace Exp240), exp225's proof/Life.lean (namespace Exp225, its
`main` dropped too) and exp253's proof/tail.lean (namespace Exp253); then tail.lean, in namespace Exp254: exp225's
kernel behind exp240's monitor, from reset to the park.

  gen.py            write Box.lean
  gen.py --check    exit 0 if Box.lean is what this writes
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "../../.."))
EXPS = os.path.join(REPO, "experiments")
EXP240 = os.path.join(EXPS, "exp240-the-code-the-box-forbids-writing", "proof", "Wx.lean")
EXP225 = os.path.join(EXPS, "exp225-the-life-every-beat-proved", "proof", "Life.lean")
EXP253 = os.path.join(EXPS, "exp253-the-cells-the-kernel-touches", "proof", "tail.lean")
OUT = os.path.join(HERE, os.environ.get("OUT", "Box.lean"))

HEAD = """/-
SPDX-License-Identifier: Apache-2.0

# exp254 — the life the box lets through

exp225's Rule 30 kernel as exp240's payload, from reset: every step the W^X box lets through, the monitor parked with
HALT 0, and the 256 generations Rule 30's.

GENERATED by gen.py: exp240's proof/Wx.lean (namespace Exp240), exp225's proof/Life.lean (namespace Exp225) and
exp253's proof/tail.lean (namespace Exp253), as their own check.sh hold them, then tail.lean (namespace Exp254).
-/
import Rv32.PrivRun
import Rv32.Refinement
import Rv32.Sandbox
import Rv32.WxBox
import Rv32.Blocks
import Rv32.Line
import Rv32.Asm
import Rv32.Reach
import Rv32.Join

set_option linter.unusedSimpArgs false
set_option linter.unusedVariables false
"""


def read(path: str) -> str:
    with open(path, encoding="utf-8") as f:
        return f.read()


def between(t: str, start: str, stop: str = "#print axioms") -> str:
    """From `start` to the first `stop`, the `#print` lines dropped."""
    t = t[t.index(start):t.index(stop)]
    return "".join(line for line in t.splitlines(keepends=True) if not line.startswith("#print")).rstrip() + "\n"


def build() -> str:
    return "\n".join([HEAD, between(read(EXP240), "namespace Exp240\n"),
                      between(read(EXP225), "namespace Exp225\n", "def main"),
                      between(read(EXP253), "namespace Exp253\n"), read(os.path.join(HERE, "tail.lean"))])


def main():
    text = build()
    if "--check" in sys.argv:
        with open(OUT, encoding="utf-8") as g:
            return 0 if g.read() == text else 1
    with open(OUT, "w", encoding="utf-8") as g:
        g.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
