"""
Writes proof/Bless.lean.

The monitor is exp240's with three charms added, so the proof is exp240's -- tools/monitor/wx.py writes it, with the
addresses moved to where this monitor has exp236's words -- and what the charms add:

  [Charm 1] boot's last two stores, the shrine's words: boot is two runs, each ending with one of them
            (`monitor_boot_config`, `monitor_boot_shrine`), so that no run steps on from a store; and before the HALT
            report, two chunks that load the shrine's words and branch to the fault report if either is wrong.
  [Charm 2] entry 3's address and configuration: other constants in exp236's definitions and boot.
  [Charm 3] between the scrub of `mscratch` and the registers, the slot's pointer and end and a zeroing loop
            (`chunks.zloop`, exp239's); `monitor_slot` is the whole of the scrub from there.

So a trap is a chunk chain from the trap vector to the slot ("_pre", five of them: a HALT, the seal's first or second
word wrong, an `ecall` for something else, a fault), then `monitor_slot`; `monitor_traps` joins them. What is written by
hand is in defs.lean (after the definitions it shares with the chunks) and tail.lean (the theorems from reset, round
after round, and the charms' theorems).

It writes proof/mutants.txt too: the charms' mutants, below, then every one of exp240's whose sed still changes what
it edits here -- the words the two monitors share, and the rules of the model -- and, as comments, those it does not
and why.

  gen.py            write Bless.lean and mutants.txt
  gen.py --check    exit 0 if both are what this writes
"""
