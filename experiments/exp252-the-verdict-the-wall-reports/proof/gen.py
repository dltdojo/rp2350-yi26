"""
Writes proof/Wall.lean.

Three proofs as their own check.sh holds them -- read here, not written again -- each with its `#print` lines and
what follows them dropped: exp238's proof/Calls.lean (namespace Exp238), exp228's proof/Script.lean (namespace
Exp228) and exp251's proof/tail.lean (namespace Exp251); then tail.lean, in namespace Exp252: exp228's kernel behind
exp238's monitor, from reset to the park.

  gen.py            write Wall.lean
  gen.py --check    exit 0 if Wall.lean is what this writes
  STUB=1 gen.py     (development only) exp238's chunks as `sorry`, written to proof/Wall_stub.lean
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "../../.."))
EXPS = os.path.join(REPO, "experiments")
EXP238 = os.path.join(EXPS, "exp238-the-call-the-monitor-checks", "proof")
EXP228 = os.path.join(EXPS, "exp228-the-script-the-kernel-runs", "proof", "Script.lean")
EXP251 = os.path.join(EXPS, "exp251-the-calls-the-script-makes", "proof", "tail.lean")
STUB = bool(os.environ.get("STUB"))
OUT = os.path.join(HERE, "Wall_stub.lean" if STUB else "Wall.lean")

HEAD = """/-
SPDX-License-Identifier: Apache-2.0

# exp252 — the verdict the wall reports

exp228's Tapscript kernel as exp238's payload, from reset: the monitor parks with the specification's verdict, the
kernel's every HASHB and CHECKSIG served by a host that hashes and checks what it is asked.

GENERATED by gen.py: exp238's proof/Calls.lean (namespace Exp238), exp228's proof/Script.lean (namespace Exp228) and
exp251's proof/tail.lean (namespace Exp251), as their own check.sh hold them, then tail.lean (namespace Exp252).
-/
import Rv32.PrivRun
import Rv32.Refinement
import Rv32.Sandbox
import Rv32.Blocks
import Rv32.Flow
import Rv32.Line
import Rv32.Asm
import Rv32.Join

set_option linter.unusedSimpArgs false
set_option linter.unusedVariables false
"""


def read(path: str) -> str:
    with open(path, encoding="utf-8") as f:
        return f.read()


def between(t: str, start: str) -> str:
    """From `start` to the first `#print`, the `#print` lines and what follows dropped."""
    t = t[t.index(start):t.index("#print axioms")]
    return t.rstrip() + "\n"


def calls238() -> str:
    if not STUB:
        return between(read(os.path.join(EXP238, "Calls.lean")), "namespace Exp238\n")
    tmp = "Calls_for_252.lean"
    env = dict(os.environ, STUB="1", OUT=tmp)
    subprocess.run([sys.executable, os.path.join(EXP238, "gen.py")], env=env, check=True)
    try:
        return between(read(os.path.join(EXP238, tmp)), "namespace Exp238\n")
    finally:
        os.remove(os.path.join(EXP238, tmp))


def build() -> str:
    return "\n".join([HEAD, calls238(), between(read(EXP228), "namespace Exp228\n"),
                      between(read(EXP251), "namespace Exp251\n"), read(os.path.join(HERE, "tail.lean"))])


def main():
    text = build()
    if "--check" in sys.argv:
        with open(OUT, encoding="utf-8") as g:
            return 0 if g.read() == text else 1
    with open(OUT, "w", encoding="utf-8") as g:
        g.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
