"""exp211 — what the shell signs with, computed here and compiled in.

  gen.py OUT.h RV32RUN

The kernels are exp213's sign.bin and exp206's kernel.bin (the verifier),
each checked against its .sha256. One seed, from random.Random(211); its
tree is tools/hazard3/mss.py's tree_of, and exp213's keygen.bin, run on the
Lean model at 0x20070000, must write the same 31 nodes. A message per leaf.

Before anything is written, for each of the 16 leaves, on the Lean model at
the chip's region: the signer's image (mss.py's sign_image) halts with 0, and
the region it leaves, with the verifier's code put over the signer's — the
shell's copying, and exp213's three_binaries — makes the verifier halt with
0: accepted. So the board has nothing to compare a signature against but the
verifier, and the verifier is proved.
"""
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.join(HERE, "..", "..", "tools", "hazard3")
sys.path.insert(0, TOOLS)
sys.path.insert(0, os.path.join(TOOLS, "shell"))
import mss  # noqa: E402
from expect import REGION_SIZE, c_bytes, kernel_bin, model  # noqa: E402

EXP = os.path.join(HERE, "..")
KERNELS = {
    "KEYGEN": "exp213-the-signer-the-verifier-accepts/keygen",
    "SIGN": "exp213-the-signer-the-verifier-accepts/sign",
    "VERIFY": "exp206-the-root-the-path-climbs/kernel",
}
LEAVES = 16


def seed_and_messages():
    rng = random.Random(211)
    seed = bytes(rng.getrandbits(8) for _ in range(32))
    msgs = [bytes(rng.getrandbits(8) for _ in range(32)) for _ in range(LEAVES)]
    return seed, msgs


def build_expect(out, rv32run):
    seed, msgs = seed_and_messages()
    nodes = mss.tree_of(seed)
    keygen, _ = kernel_bin(os.path.join(EXP, KERNELS["KEYGEN"]))
    sign, sign_sha = kernel_bin(os.path.join(EXP, KERNELS["SIGN"]))
    verify, verify_sha = kernel_bin(os.path.join(EXP, KERNELS["VERIFY"]))

    ran, region = model(rv32run, mss.keygen_image(keygen, seed).ljust(REGION_SIZE, b"\0"), 100000)
    if not ran.startswith("halt code=00000000") or region[mss.K_TREE:mss.K_TREE + 31 * 32] != b"".join(nodes):
        sys.exit(f"gen.py: keygen on the model said {ran}, or its tree is not mss.py's")
    print(f"keygen     {ran}  tree is mss.py's")

    for leaf in range(LEAVES):
        s_ran, s_reg = model(rv32run, mss.sign_image(sign, seed, nodes, leaf, msgs[leaf]).ljust(REGION_SIZE, b"\0"),
                             100000)
        image = bytearray(s_reg)
        image[:len(verify)] = verify
        v_ran, _ = model(rv32run, bytes(image), 100000)
        if not (s_ran.startswith("halt code=00000000") and v_ran.startswith("halt code=00000000")):
            sys.exit(f"gen.py: leaf {leaf}: sign said {s_ran}, verify said {v_ran}")
        print(f"leaf {leaf:2}    sign {s_ran:32}  verify {v_ran}", flush=True)

    with open(out, "w") as f:
        f.write("// Generated by exp211/gen.py from exp213's and exp206's kernels and tools/hazard3/mss.py. "
                "Do not edit.\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define TREE_LEN {31 * 32}\n")
        for name in ("S_MSG", "S_IDX", "S_SEED", "S_TREE"):
            f.write(f"#define {name} 0x{getattr(mss, name):04x}u\n")
        f.write("\nstruct fill { uint16_t at, len; };     // 0xee before the kernel runs\n")
        f.write(f"static const struct fill S_FILL[{len(mss.S_FILL)}] = {{" +
                ", ".join(f"{{0x{a:04x}, {n}}}" for a, n in mss.S_FILL) + "};\n")
        for name, b, sha in (("SIGN", sign, sign_sha), ("VERIFY", verify, verify_sha)):
            f.write(f"\n#define {name}_LEN {len(b)}\n")
            f.write(f"static const uint8_t {name}_SHA[32] = {{{c_bytes(bytes.fromhex(sha))}}};\n")
            f.write(f"static const uint8_t {name}_BIN[{len(b)}] = {{\n")
            for o in range(0, len(b), 16):
                f.write(f"    {c_bytes(b[o:o + 16])},\n")
            f.write("};\n")
        f.write(f"\nstatic const uint8_t SEED[32] = {{{c_bytes(seed)}}};\n")
        f.write("static const uint8_t TREE[TREE_LEN] = {\n")
        for n in nodes:
            f.write(f"    {c_bytes(n)},\n")
        f.write("};\n")
        f.write(f"static const uint8_t MSG[{LEAVES}][32] = {{\n")
        for m in msgs:
            f.write(f"    {{{c_bytes(m)}}},\n")
        f.write("};\n")
    print(f"expect.h: {LEAVES} leaves, each signed and accepted on the model")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    build_expect(sys.argv[1], sys.argv[2])
