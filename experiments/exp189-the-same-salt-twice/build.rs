// Two arms, and one build input that deliberately does not exist.
//
// exp171 and exp174 each shipped a `UP=none` arm, because "does this device
// wait for a person" was the thing being compared and a half of a comparison
// is not a comparison. Here it is not the comparison — `constant` against
// `bank8` is — and a build of a *key release* device that hands the key to
// nobody in particular is an artefact worth not having lying around. The
// `ga-nopress` case is produced by not pressing, which costs nothing and
// proves the same thing about the firmware that is actually shipped.

use std::{env, fs, path::PathBuf};

fn main() {
    // Where the device secret comes from.
    //   constant — exp171's compiled-in test key. exp175's forge.py must find
    //              it: that is the control saying the attack still works.
    //   bank8    — exp181's key, reconstructed from SRAM at boot. forge.py
    //              must find nothing. Inherits exp182's cost in full: a board
    //              straight from `yi26 flash` can do nothing until the power
    //              has been away once, because flashing zeroes the SRAM the
    //              key comes from.
    let key = env::var("EXP189_KEY").unwrap_or_else(|_| "constant".to_string());
    let from_sram = match key.as_str() {
        "constant" => false,
        "bank8" => true,
        other => panic!("EXP189_KEY must be `constant` or `bank8`, not `{other}`"),
    };

    // exp174: below the ceiling the packet changes nothing, and it is what
    // makes this keep working when a person is slow. Off is a build input so
    // that the ceiling can be measured again rather than assumed to have
    // stayed where exp174 found it.
    let keepalive = !matches!(env::var("EXP189_KEEPALIVE").as_deref(), Ok("off" | "0" | "false"));

    // How long somebody who is not going to press has. `ga-nopress` waits it
    // out, so a long default costs the transcript real seconds.
    let timeout: u64 = env::var("EXP189_TIMEOUT_MS").ok().and_then(|v| v.parse().ok()).unwrap_or(20_000);

    // exp188's engine reads these; they are emitted rather than removed so the
    // inherited code compiles unchanged. `WAIT_FOR_USER` is hard true for the
    // reason at the top of this file: the press is not a build input here.
    let hold: u64 = env::var("EXP189_HOLD_MS").ok().and_then(|v| v.parse().ok()).unwrap_or(0);
    let reset_window: u64 = env::var("EXP189_RESET_WINDOW_SECS").ok().and_then(|v| v.parse().ok()).unwrap_or(10);
    // How often the BOOTSEL line is sampled. `crates/bootsel` says in its own
    // documentation: "Do not poll it in a tight loop ... something like every
    // 20 ms is plenty for a button." exp174 polls at 20; the engine inherited
    // here polls at 10. It is a build input so the difference can be measured
    // rather than argued about.
    let poll: u64 = env::var("EXP189_PRESENCE_POLL_MS").ok().and_then(|v| v.parse().ok()).unwrap_or(20);
    let max_rk: usize = env::var("EXP189_MAX_RK").ok().and_then(|v| v.parse().ok()).unwrap_or(16);

    let out = PathBuf::from(env::var_os("OUT_DIR").unwrap());
    fs::write(
        out.join("exp189_config.rs"),
        format!(
            "// generated by build.rs — do not edit\n\
             /// `constant` or `bank8` — printed on the first log line, because a\n\
             /// transcript that does not say which arm produced it is not evidence.\n\
             pub const KEY_SOURCE: &str = {key:?};\n\
             /// Does the device secret come out of SRAM rather than out of the image?\n\
             pub const KEY_FROM_SRAM: bool = {from_sram};\n\
             pub const UP_MODE: &str = \"button\";\n\
             /// Always true. exp189 has no arm that hands a key to nobody.\n\
             pub const WAIT_FOR_USER: bool = true;\n\
             /// Say \"still here\" while waiting for a finger.\n\
             pub const KEEPALIVE: bool = {keepalive};\n\
             pub const HOLD_MS: u64 = {hold};\n\
             /// How long a person who is not there has, in ms.\n\
             pub const TIMEOUT_MS: u64 = {timeout};\n\
             pub const RESET_WINDOW_SECS: u64 = {reset_window};\n\
             pub const MAX_RESIDENT_KEYS: usize = {max_rk};\n\
             /// Milliseconds between BOOTSEL samples while waiting for a person.\n\
             pub const PRESENCE_POLL_MS: u64 = {poll};\n"
        ),
    )
    .unwrap();

    // A cfg, not just a const: exp175's forgery searches the *image*, so a
    // secret that is compiled in and never used is still a secret anybody with
    // the file has. The bank8 arm has to be built without one, and the first
    // version of it was not — forge.py minted an assertion from that image and
    // said so.
    if from_sram {
        println!("cargo:rustc-cfg=bank8");
    }
    println!("cargo:rustc-check-cfg=cfg(bank8)");

    for var in ["EXP189_KEY", "EXP189_KEEPALIVE", "EXP189_TIMEOUT_MS", "EXP189_HOLD_MS", "EXP189_RESET_WINDOW_SECS", "EXP189_MAX_RK", "EXP189_PRESENCE_POLL_MS"] {
        println!("cargo:rerun-if-env-changed={var}");
    }
    println!("cargo:rerun-if-changed=build.rs");
}
