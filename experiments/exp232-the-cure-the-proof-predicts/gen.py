"""exp232 — what the shell compiles in, computed here.

  gen.py OUT.h RV32RUN

  KERNEL, KERNEL_SHA   kernel.bin, checked against kernel.sha256
  INSTRET              the Hazard3 RTL's minstret for the image, the count the
                       chip is asked to match on every run; the same for two
                       different patients, since the theorem's count does not
                       depend on them — after the Lean model has run one
                       patient at the chip's region and halted with 0 after
                       exactly 3081, leaving cure.py's generations and nothing
                       else
  DAYS … SEARCH_SEED   the trial's constants, cure.py's
  ANSWER, ACCEPTED, RELAPSING, LOOPHOLE
                       what cure.py's search finds, which the chip's must
"""
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "tools", "hazard3", "shell"))
import cure  # noqa: E402
from expect import c_bytes, kernel_bin, model, rtl  # noqa: E402


def cure_header(out, rv32run):
    kernel, sha = kernel_bin(os.path.join(HERE, "kernel"))
    answer, accepted, relapsing, loophole = cure.search()
    t = cure.lump(6)
    img = cure.image(kernel, t, ~t & cure.M, answer)
    ran, region = model(rv32run, img, 4000)
    if ran != "halt code=00000000 count=3081":
        sys.exit(f"gen.py: the model did not halt with 0 after 3081: {ran}")
    want = bytearray(img) + bytearray(len(region) - len(img))
    want[cure.HIST_OFF:cure.HIST_OFF + 512] = cure.lifetime_bytes(t, ~t & cure.M, answer)
    if region != bytes(want):
        sys.exit("gen.py: the model's region is not the image with cure.py's history")
    counts = set()
    for args in ((t, ~t & cure.M, answer), (cure.lump(3, 9), cure.M ^ cure.lump(3, 9), loophole)):
        r = rtl(cure.image(kernel, *args))
        if not r.startswith("halt code=00000000 instret="):
            sys.exit(f"gen.py: the RTL did not halt with 0: {r}")
        counts.add(int(r.split("instret=")[1].split()[0]))
    if len(counts) != 1:
        sys.exit(f"gen.py: the RTL counted differently for two patients: {counts}")
    instret = counts.pop()
    with open(out, "w") as f:
        f.write("// Generated by exp232/gen.py. Do not edit.\n#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define KERNEL_LEN {len(kernel)}\n")
        f.write(f"#define INSTRET {instret}u   // the RTL harness's minstret, whatever the patient\n")
        for name in ("DAYS", "DETECT", "TISSUE_MIN", "MUT_BITS", "CANDIDATES", "SEARCH_SEED"):
            f.write(f"#define {name} {getattr(cure, name)}u\n")
        f.write(f"#define WIDTH_MAX {max(cure.WIDTHS)}u\n")
        f.write(f"#define ANSWER {answer:#x}u\n#define ACCEPTED {accepted}u\n")
        f.write(f"#define RELAPSING {relapsing}u\n#define LOOPHOLE {loophole:#x}u\n")
        f.write("static const uint8_t KERNEL[KERNEL_LEN] = {" + c_bytes(kernel) + "};\n")
        f.write("static const uint8_t KERNEL_SHA[32] = {" + c_bytes(bytes.fromhex(sha)) + "};\n")
    print(f"{out}: kernel {sha[:16]}…, model 3081, RTL minstret {instret}, "
          f"search {accepted} accepted, {relapsing} relapsing, answer {answer:06x}")


def plan(answer):
    """The protocol's SHA-256, as the shell hashes it: eight little-endian words."""
    words = [answer, cure.DAYS, cure.DETECT, cure.TISSUE_MIN, max(cure.WIDTHS), cure.MUT_BITS,
             cure.CANDIDATES, cure.SEARCH_SEED]
    return hashlib.sha256(b"".join(w.to_bytes(4, "little") for w in words)).digest()


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    cure_header(sys.argv[1], sys.argv[2])
