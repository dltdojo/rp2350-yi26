"""
Writes proof/Rounds.lean.

What exp254's proof/gen.py writes into its Box.lean -- exp240's proof/Wx.lean, exp225's proof/Life.lean and exp253's
proof/tail.lean, as their own check.sh hold them -- with exp254's proof/tail.lean after it, each with its `#print`
lines dropped; then tail.lean, in namespace Exp255: exp225's kernel behind exp240's monitor, round after round. The
reading and the cutting are exp254's gen.py's, loaded from it.

  gen.py            write Rounds.lean
  gen.py --check    exit 0 if Rounds.lean is what this writes
"""
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "../../.."))
EXP254 = os.path.join(REPO, "experiments", "exp254-the-life-the-box-lets-through", "proof")
OUT = os.path.join(HERE, os.environ.get("OUT", "Rounds.lean"))

_spec = importlib.util.spec_from_file_location("gen254", os.path.join(EXP254, "gen.py"))
g254 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(g254)

HEAD = """/-
SPDX-License-Identifier: Apache-2.0

# exp255 — the lives, round after round

exp225's Rule 30 kernel as exp240's payload, round after round: every round parks with HALT 0 and the history Rule 30
of the seed it found, and with the host copying each round's last generation into the seed, the rounds together are
Rule 30 from the first seed.

GENERATED by gen.py: exp240's proof/Wx.lean (namespace Exp240), exp225's proof/Life.lean (namespace Exp225), exp253's
and exp254's proof/tail.lean (namespaces Exp253 and Exp254), as their own check.sh hold them, then tail.lean
(namespace Exp255).
-/
""" + g254.HEAD[g254.HEAD.index("import "):]


def build() -> str:
    read, between = g254.read, g254.between
    return "\n".join([HEAD, between(read(g254.EXP240), "namespace Exp240\n"),
                      between(read(g254.EXP225), "namespace Exp225\n", "def main"),
                      between(read(g254.EXP253), "namespace Exp253\n"),
                      between(read(os.path.join(EXP254, "tail.lean")), "namespace Exp254\n"),
                      read(os.path.join(HERE, "tail.lean"))])


def main():
    text = build()
    if "--check" in sys.argv:
        with open(OUT, encoding="utf-8") as g:
            return 0 if g.read() == text else 1
    with open(OUT, "w", encoding="utf-8") as g:
        g.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
