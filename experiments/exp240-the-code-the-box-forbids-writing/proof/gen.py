"""
Writes proof/Wx.lean.

The proof runs `monitorCode` on `PrivMachine` in short runs ("chunks"), as exp238's and exp239's do, with the machinery in
tools/monitor/chunks.py. The monitor's words are exp236's but for the seven that boot adds to set three PMP entries
instead of one, and the one more it spends on writing every CSR the model has (`mstatus` whole, where exp236 cleared
`MPP` with three words, and `pmpaddr3`, `mcause`, and `mtval`, which Hazard3 hardwires to 0 and the model too), so everything from the trap vector on is where exp236's was,
0x20 bytes further on: the definitions and the second half of boot are exp236's text with the PMP values changed and
the addresses moved (`shift`); the first half of boot is new, since it starts from any CSRs and exp236's starts from
reset's; and the proof of the handler is a table of chunks, as exp239's is, from the trap vector to the park loop. All
of that is in tools/monitor/wx.py, which exp245 shares; what is this monitor's alone is here.

What is written by hand is in defs.lean (after the definitions it shares with the chunks) and tail.lean (the theorems
that join them: from reset, and round after round).

  gen.py            write Wx.lean
  gen.py --check    exit 0 if Wx.lean is what this writes
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "../../.."))
OUT = os.path.join(HERE, os.environ.get("OUT", "Wx.lean"))

sys.path.insert(0, os.path.join(REPO, "tools", "monitor"))
import chunks
import wx
from chunks import Chunk
from wx import h, HC, HCN, IS_HALT, KARG, ZALL, ZW2, CSR0, CSRZ, FAULT_REPORT, HALT_REPORT, ev, evs, EXIT

WORDS = 151
BYTES = WORDS * 4
SH = 0x20                              # eight words more of boot than exp236's: where its trap vector was, plus this
CFG, A0, A1, A2 = "0x001b1b1d#32", "0x2000400f#32", "0x200041ff#32", "0x20007dff#32"
BOOT_STEPS = 28            # exp236's 20, the seven words the entries add, and one for the CSRs written whole
ALL_STEPS = 61             # exp236's 53 and the same
wx.configure(WORDS, BOOT_STEPS, ALL_STEPS, [(0, 0x400, SH)], CFG, A0, A1, A2)

HEAD = """/-
SPDX-License-Identifier: Apache-2.0

# exp240 — the code the box forbids writing

What `monitor.bin` does, proved by running its own words on `PrivMachine`.

GENERATED by gen.py: the definitions and the proof of boot are exp236's with the PMP changed and the addresses moved;
the short runs ("chunks") of the handler are one theorem shape with one proof; the definitions that come after them are
in defs.lean and the theorems that join them are in tail.lean.
-/
import Rv32.PrivRun
import Rv32.Refinement
import Rv32.Sandbox
import Rv32.WxBox

set_option linter.unusedSimpArgs false
set_option linter.unusedVariables false

namespace Exp240
open Rv32
open Rv32.Priv
open Rv32.Refinement

/-- The words of `monitor.bin`, from `0x80000000`. -/
"""

def read(name: str) -> str:
    with open(os.path.join(HERE, name), encoding="utf-8") as f:
        return f.read()


def definitions(t: str) -> str:
    return wx.definitions(t, "/-- What boot's first twenty-eight steps leave in the CSRs, whatever they held: trap vector, stack pointer\n"
                             "    for traps, the three PMP entries (code, data, stack) and the fourth's address zero, the `mret` target,\n"
                             "    counters frozen at zero, `mstatus` and `mcause` zero. -/")


def boot_proof(t: str) -> str:
    return wx.boot_proof(t, wx.boot_config(f"0x{0x80000090 + SH:08x}#32"))


# ---- the chunks: one theorem shape, from tools/monitor/chunks.py

T = wx.Table(wx.handler_chunks())
wx.handler_phases(T)
CHUNKS, CH = T.chunks, T.by
S, phase = T.S, T.phase


def scenario(name, doc, hyps, steps_, *, regs, io):
    c = Chunk(name, doc, 0, h(0x114), h(wx.PARK), pbind="", hyps=hyps, csr_in=CSR0, csr_out=CSRZ,
              words=ZW2, regs=regs, steps=steps_, io=io)
    return phase(c)


scenario("monitor_halt",
         "`ecall` with `t0 = 1`: the HALT reported, the saved words and `mscratch` zero, every register but `a0` zero, the park loop.",
         HC + IS_HALT(True),
         [S("monitor_enter", resolve="hc"),
          S("call_is_halt", args=[KARG], hyps={"hk": "w1_0"}, resolve="ofNat_toNat_mod, ht0"),
          S("monitor_halt_exit"), S("monitor_regs", last=True)],
         regs=ZALL, io=evs(*HALT_REPORT, ev(EXIT, "s.core.reg 10#5")))
scenario("monitor_fault_cause",
         "A trap that is not an `ecall`: the fault reported, `a0 = 1`, every other register zero, the park loop.",
         HCN,
         [S("monitor_enter", resolve="hc"), S("monitor_fault_exit"), S("monitor_regs", last=True)],
         regs=ZALL + ", (10, 1#32)", io=evs(*FAULT_REPORT, ev(EXIT, "1#32")))
scenario("monitor_fault_syscall",
         "An `ecall` whose `t0` is not 1: the fault reported, `a0 = 1`, every other register zero, the park loop.",
         HC + IS_HALT(False),
         [S("monitor_enter", resolve="hc"),
          S("call_is_halt", args=[KARG], hyps={"hk": "w1_0"}, resolve="ofNat_toNat_mod, ht0"),
          S("monitor_fault_exit"), S("monitor_regs", last=True)],
         regs=ZALL + ", (10, 1#32)", io=evs(*FAULT_REPORT, ev(EXIT, "1#32")))


def trap_glue() -> str:
    """`monitor_traps`: from the trap vector, the three ways in."""
    def case(name, args, a0, steps):
        fix = "regs_scrubbed" if name == "monitor_halt" else "regs_scrubbed_fault"
        return f"""      obtain ⟨p, a, h, m', cc, ho, io, w0, w1, w2, w3, sv, fr, r⟩ := {name} env M0 u hS ms e c m cy hpc hcs{args}
      obtain ⟨k1, k2⟩ := {fix} r
      have hn : trapSteps u = {steps} := by simp [trapSteps, hcu, hc{", ht0" if "ht0" in args else ""}]
      rw [hn]
      refine ⟨⟨p, h, m', by rw [cc]; rfl, w0, w1, ?_, k2⟩, a, frameSP_of fr sv, by rw [cc]; rfl, ho, ?_⟩
      · rw [k1]
{a0}
      · rw [io]
        simp [trapIo, faultIo, haltIo, exitCode, hcs, csrsH, hcu, hc{", ht0" if "ht0" in args else ""}]
"""

    halt = case("monitor_halt", " hc ht0", "        simp [exitCode, hcu, hc, ht0]", CH["monitor_halt"].n)
    cause = case("monitor_fault_cause", " hc", "        simp [exitCode, hcu, hc]", CH["monitor_fault_cause"].n)
    sysc = case("monitor_fault_syscall", " hc ht0", "        simp [exitCode, hcu, hc, ht0]", CH["monitor_fault_syscall"].n)
    return f"""
/-! ## However the payload leaves, the monitor parks -/

/-- **A trap, and what the monitor makes of it.** From the trap vector, whatever the payload left in its registers
    and memory, and whatever it was that trapped -- an `ecall` for HALT, an `ecall` for anything else, or a fault --
    the monitor parks with the exit code `exitCode u` (the payload's own `a0` for a HALT, 1 for the rest), every other
    register zero, `mscratch` and the saved words zero, its own words in place, and **every byte of memory but its stack
    words and its report words as the payload left it**: the code, the data, the stack, the rest; the PMP as boot set it;
    and the host has heard `trapIo u`, the report for the way it trapped and then the exit code. -/
theorem monitor_traps (env : Rv32.Env) (M0 : Word → Byte) (u : PrivMachine)
    (hS : HState env M0 u) (ms : MStatus) (e c m cy : Word)
    (hpc : u.core.pc = {h(0x114)}#32) (hcs : u.csrs = csrsH ms e c m cy {{}} 0x80008000#32) :
    Parked (PrivMachine.run env (trapSteps u) u) (exitCode u) ∧
      Agree M0 (PrivMachine.run env (trapSteps u) u).core.mem 0x80000000 {BYTES} ∧
      FrameSP u.core.mem (PrivMachine.run env (trapSteps u) u).core.mem ∧
      (PrivMachine.run env (trapSteps u) u).csrs.pmpcfg0 = {CFG} ∧
      (PrivMachine.run env (trapSteps u) u).host = u.host ∧
      (PrivMachine.run env (trapSteps u) u).io = u.io ++ trapIo u := by
  have hcu : u.csrs.mcause = c := by rw [hcs]; rfl
  by_cases hc : c = 8#32
  · by_cases ht0 : u.core.reg 5#5 = 1#32
    · -- an `ecall` for HALT
{halt}    · -- an `ecall` for anything else
{sysc}  · -- a trap that is not an `ecall`
{cause}
"""


def build(chunks_text: str) -> str:
    f = chunks.from_236("Exp240")
    parts = [HEAD, wx.monitor_code(os.path.join(HERE, "..")), wx.length(), f["step"], definitions(wx.shift(f["defs"])),
             chunks.FRAME, chunks.WRITELE4, boot_proof(wx.shift(f["boot"])), f["helpers"], f["ofnat"], read("defs.lean"),
             chunks_text, wx.REG_LEMMAS,
             trap_glue(), read("tail.lean")]
    return "\n".join(parts)


def main():
    only = os.environ.get("ONLY")
    cs = [c for c in CHUNKS if not only or not (c.steps or c.custom) or c.name in only.split(",")]
    text = build("\n".join(c.lean() for c in cs))
    if "--check" in sys.argv:
        with open(OUT, encoding="utf-8") as g:
            return 0 if g.read() == text else 1
    with open(OUT, "w", encoding="utf-8") as g:
        g.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
