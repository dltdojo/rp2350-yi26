def h(x: int) -> str:
    """An address inside the monitor, after boot: exp236's offset, moved on by the words boot adds."""
    return f"0x{0x80000000 + x + SH:08x}"


def shift(text: str) -> str:
    """exp236's text with every address from its boot's 0x90 on moved by `SH`."""
    def move(m):
        v = int(m.group(1), 16)
        return f"0x8000{v + SH:04x}" if 0x90 <= v < 0x400 else m.group(0)
    return re.sub(r"0x8000([0-9a-f]{4})\b", move, text)


def swap(text: str, old: str, new: str, count: int = 1) -> str:
    """`text` with `old` replaced by `new`, `count` times exactly: exp236 changing under us is a failure here."""
    assert text.count(old) == count, f"{old[:60]!r} occurs {text.count(old)} times, not {count}"
    return text.replace(old, new)


