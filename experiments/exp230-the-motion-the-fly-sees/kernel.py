"""exp230 — the fly's kernel, written with labels, emitted as Lean.

A Hassenstein–Reichardt detector, one bit a cell, on a ring of 32 cells. The
kernel reads 257 frames of the ring, one word each, and for each of the 256
steps between them counts what moved one cell up and what moved one cell down:

  up   = popcount(rotl(before, 1) & now)
  down = popcount(rotr(before, 1) & now)

It writes both counts for every step, then their totals, and halts with 0.
RV32IM has no rotate, so each is two shifts and an OR; and no popcount, so
one loop of 32 rounds counts both words a bit at a time. Nothing here needs
to hide what it reads: the frames are what the fly sees.

  kernel.py           rewrite the generated block in proof/Fly.lean
  kernel.py --check   exit 1 if the block is not what this would write

The layout, from base (s1 holds base):

  0x0000  the kernel
  0x0100  UP    the total moved up, a word
  0x0104  DOWN  the total moved down, a word
  0x0200  the frames, 257 words: frame t at 0x200 + 4t
  0x0800  the steps, 256 of them: step t's up at 0x800 + 8t, its down at + 4
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROOF = os.path.join(HERE, "proof", "Fly.lean")
sys.path.insert(0, os.path.join(HERE, "..", "..", "tools", "lean"))
from kasm import Kernel, splice  # noqa: E402

UP, DOWN, FRAMES, STEPS, N = 0x100, 0x104, 0x200, 0x800, 256

K = Kernel()
ins = K.ins


def fly_kernel():
    K.label("ENTRY")
    ins("auipc", "s1", 0)
    ins("opi", "addi", "a0", "s1", FRAMES)      # frame t
    ins("opi", "addi", "a2", "s1", 0x400)       # step t, at 0x800: two halves of
    ins("opi", "addi", "a2", "a2", 0x400)       # an immediate too wide for one
    ins("opi", "addi", "s2", "zero", 0)         # total up
    ins("opi", "addi", "s3", "zero", 0)         # total down
    ins("opi", "addi", "t1", "zero", N)         # steps to go

    K.label("STEP")
    ins("ld", "lw", "t2", "a0", 0)              # the frame before
    ins("ld", "lw", "t3", "a0", 4)              # the frame now
    ins("sh", "slli", "t4", "t2", 1)            # before, moved up
    ins("sh", "srli", "t5", "t2", 31)
    ins("op", "or", "t4", "t4", "t5")
    ins("sh", "srli", "t5", "t2", 1)            # before, moved down
    ins("sh", "slli", "t6", "t2", 31)
    ins("op", "or", "t5", "t5", "t6")
    ins("op", "and", "t4", "t4", "t3")          # what moved up
    ins("op", "and", "t5", "t5", "t3")          # what moved down
    ins("opi", "addi", "a3", "zero", 0)
    ins("opi", "addi", "a4", "zero", 0)
    ins("opi", "addi", "t0", "zero", 32)

    K.label("BIT")
    ins("opi", "andi", "t6", "t4", 1)
    ins("op", "add", "a3", "a3", "t6")
    ins("sh", "srli", "t4", "t4", 1)
    ins("opi", "andi", "t6", "t5", 1)
    ins("op", "add", "a4", "a4", "t6")
    ins("sh", "srli", "t5", "t5", 1)
    ins("opi", "addi", "t0", "t0", -1)
    ins("br", "bne", "t0", "zero", "BIT")

    ins("st", "sw", "a2", "a3", 0)
    ins("st", "sw", "a2", "a4", 4)
    ins("op", "add", "s2", "s2", "a3")
    ins("op", "add", "s3", "s3", "a4")
    ins("opi", "addi", "a0", "a0", 4)
    ins("opi", "addi", "a2", "a2", 8)
    ins("opi", "addi", "t1", "t1", -1)
    ins("br", "bne", "t1", "zero", "STEP")

    K.label("DONE")
    ins("st", "sw", "s1", "s2", UP)
    ins("st", "sw", "s1", "s3", DOWN)
    ins("opi", "addi", "a0", "zero", 0)
    ins("opi", "addi", "t0", "zero", 1)
    ins("ecall")


def fly_block():
    labels, code = K.assemble()
    lines = ["-- BEGIN generated by kernel.py — do not edit", ""]
    lines.append("/-- Where each label is: an instruction number. -/")
    for name, k in labels.items():
        lines.append(f"def {name} : Nat := {k}")
    lines.append("")
    lines.append(f"/-- The kernel, {len(code)} instructions. -/")
    lines.append("def kernel : List Instr := [")
    for k, text in enumerate(code):
        lines.append(f"  {text}{',' if k + 1 < len(code) else ' ]'}")
    lines.append("")
    lines.append("-- END generated by kernel.py")
    return "\n".join(lines)


fly_kernel()

if __name__ == "__main__":
    text = open(PROOF).read()
    new = splice(text, fly_block(), "kernel.py")
    if sys.argv[1:] == ["--check"]:
        sys.exit(0 if new == text else 1)
    open(PROOF, "w").write(new)
    labels, code = K.assemble()
    print(f"proof/Fly.lean: {len(code)} instructions, {len(labels)} labels")
