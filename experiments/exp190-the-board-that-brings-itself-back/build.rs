// How this firmware kills itself. A safety net nobody has dropped a weight on
// is not a safety net, so the weight is a build input.

use std::{env, fs, path::PathBuf};

fn main() {
    let die = env::var("EXP190_DIE").unwrap_or_else(|_| "never".to_string());
    match die.as_str() {
        // The control. It gets up and stays up, and every claim below is worth
        // nothing without it.
        "never" => {}
        // Dies **before** saying it is reachable, by a fault. Three of these in
        // a row and the board should hand itself to the bootloader.
        "early" => {}
        // Dies **after** saying it is reachable. It must NOT be handed over:
        // a board that got up is one a host can still reboot at 1200 baud, and
        // an escape there would turn an ordinary crash into a bootloader.
        "late" => {}
        // Stops without dying — a busy loop with interrupts off, which raises
        // no exception at all. This is the case no fault handler catches and
        // the reason the watchdog is armed rather than trusted to a handler.
        "hang" => {}
        other => panic!("EXP190_DIE must be never|early|late|hang, not `{other}`"),
    }
    let out = PathBuf::from(env::var_os("OUT_DIR").unwrap());
    fs::write(
        out.join("exp190_config.rs"),
        format!("// generated by build.rs — do not edit\npub const DIE: &str = {die:?};\n"),
    )
    .unwrap();
    println!("cargo:rerun-if-env-changed=EXP190_DIE");
    println!("cargo:rerun-if-changed=build.rs");
}
