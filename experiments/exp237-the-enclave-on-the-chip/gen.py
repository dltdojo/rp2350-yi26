"""
Header generator for exp237's C launcher.

Assembles the monitor and the four test payloads (each through the C
preprocessor, so they share shell/mem_layout.h with the C shell), reads exp229's
kernel.bin, and writes build/payload.h with all six images as C byte arrays.
Also importable: emutest.py takes the same images from build_images().
"""

import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "../.."))
sys.path.insert(0, os.path.join(REPO, "tools/monitor"))
import asm

MONITOR_BASE = 0x20040000
PAYLOAD_BASE = 0x20050000
KERNEL_BIN = os.path.join(REPO, "experiments/exp229-the-remainder-the-kernel-keeps/kernel.bin")

# name -> (source, load address)
SOURCES = {
    "MONITOR": ("monitor_chip.S", MONITOR_BASE),
    "CANARY": ("payload_canary.S", PAYLOAD_BASE),
    "READ": ("payload_read.S", PAYLOAD_BASE),
    "WRITE": ("payload_write.S", PAYLOAD_BASE),
    "BADCALL": ("payload_badcall.S", PAYLOAD_BASE),
}


def assemble_pp(src: str, base: int, build: str) -> bytes:
    stem = os.path.splitext(os.path.basename(src))[0]
    pp = os.path.join(build, stem + ".pp.S")
    out = os.path.join(build, stem + ".bin")
    subprocess.run(["clang", "--target=riscv32-unknown-elf", "-E", "-P", "-x", "assembler-with-cpp",
                    "-I", os.path.join(HERE, "shell"), os.path.join(HERE, "shell", src), "-o", pp],
                   check=True)
    asm.assemble(pp, out, base)
    with open(out, "rb") as f:
        return f.read()


def build_images(build: str) -> dict:
    os.makedirs(build, exist_ok=True)
    images = {name: assemble_pp(src, base, build) for name, (src, base) in SOURCES.items()}
    with open(KERNEL_BIN, "rb") as f:
        images["KERNEL"] = f.read()
    return images


def words_used(image: bytes) -> int:
    """32-bit words that are not zero: the monitor's instructions, without the .org padding."""
    return sum(1 for i in range(0, len(image), 4) if image[i:i + 4] != b"\0\0\0\0")


def write_array(f, name: str, data: bytes):
    f.write(f"#define {name}_BIN_LEN {len(data)}u\n")
    f.write(f"static const uint8_t {name}_BIN[] = {{\n")
    for i, b in enumerate(data):
        f.write(f"0x{b:02x},")
        if (i + 1) % 16 == 0:
            f.write("\n")
    f.write("\n};\n\n")


def generate_payload_h(out_h: str):
    build = os.path.dirname(os.path.abspath(out_h))
    images = build_images(build)
    with open(out_h, "w") as f:
        f.write("// SPDX-License-Identifier: Apache-2.0\n")
        f.write("// Generated by gen.py for exp237 — DO NOT EDIT DIRECTLY\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        for name in ("MONITOR", "KERNEL", "CANARY", "READ", "WRITE", "BADCALL"):
            write_array(f, name, images[name])
        f.write(f"#define MONITOR_WORDS {words_used(images['MONITOR'])}u\n")
    print(f"Generated {out_h} (monitor: {len(images['MONITOR'])} B, "
          f"{words_used(images['MONITOR'])} words, kernel: {len(images['KERNEL'])} B)")


if __name__ == "__main__":
    generate_payload_h(sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "build/payload.h"))
