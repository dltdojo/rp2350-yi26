"""
Header generator for exp237's C launcher.

Assembles monitor_chip.S into monitor_chip.bin, reads exp229's kernel.bin,
and generates build/payload.h containing both binary images as C byte arrays.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "../.."))
sys.path.insert(0, os.path.join(REPO, "tools/monitor"))
import asm

def generate_payload_h(out_h: str):
    os.makedirs(os.path.dirname(out_h), exist_ok=True)
    mon_src = os.path.join(HERE, "shell/monitor_chip.S")
    mon_bin = os.path.join(HERE, "build/monitor_chip.bin")
    kernel_bin = os.path.join(REPO, "experiments/exp229-the-remainder-the-kernel-keeps/kernel.bin")

    asm.assemble(mon_src, mon_bin, 0x20000000)

    with open(mon_bin, "rb") as f:
        mon_data = f.read()

    with open(kernel_bin, "rb") as f:
        kernel_data = f.read()

    with open(out_h, "w") as f:
        f.write("// SPDX-License-Identifier: Apache-2.0\n")
        f.write("// Generated by gen.py for exp237 — DO NOT EDIT DIRECTLY\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")

        f.write(f"#define MONITOR_BIN_LEN {len(mon_data)}u\n")
        f.write("static const uint8_t MONITOR_BIN[] = {\n")
        for i, b in enumerate(mon_data):
            f.write(f"0x{b:02x},")
            if (i + 1) % 16 == 0:
                f.write("\n")
        f.write("\n};\n\n")

        f.write(f"#define KERNEL_BIN_LEN {len(kernel_data)}u\n")
        f.write("static const uint8_t KERNEL_BIN[] = {\n")
        for i, b in enumerate(kernel_data):
            f.write(f"0x{b:02x},")
            if (i + 1) % 16 == 0:
                f.write("\n")
        f.write("\n};\n\n")

        f.write("#define EXP229_ADD_INSTRET 331u\n")
        f.write("#define EXP229_SUB_INSTRET 238u\n")
        f.write("#define EXP229_MUL_INSTRET 1903u\n")

    print(f"Generated {out_h} (monitor: {len(mon_data)} B, kernel: {len(kernel_data)} B)")

if __name__ == "__main__":
    out_h = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "build/payload.h")
    generate_payload_h(out_h)
