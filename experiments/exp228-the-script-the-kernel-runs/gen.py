"""exp228 — what the shell compiles in, computed here.

  gen.py OUT.h RV32RUN

  KERNEL, KERNEL_SHA   kernel.bin (the kernel and its table, 0x1400 bytes),
                       checked against kernel.sha256
  MSG                  the message every CHECKSIG is about: the shell's, as
                       BIP341's signature hash would be
  CASES                every hand case in cases.py: its script, its initial
                       stack (bottom first) in POOL as length-prefixed
                       elements, and the verdict script.py gives it with
                       BIP340 as the signature check — after the Lean model,
                       told the one valid (key, signature) pair, has halted
                       with that same code; and minstret as the RTL counts
                       it: the model's count, 4 of the harness's around the
                       run, and 4 more for each call the kernel makes, which
                       script.py counts as it calls its hash and its check
"""
import hashlib
import os
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "..", "tools", "hazard3", "shell"))
from expect import c_bytes, kernel_bin, model  # noqa: E402
import cases  # noqa: E402
from script import script_verdict  # noqa: E402

FUEL = 200000


def header(out, rv32run):
    kernel, sha = kernel_bin(os.path.join(HERE, "kernel"))
    sigs = tempfile.NamedTemporaryFile("w", suffix=".sigs", delete=False)
    sigs.write(f"{cases.KEY.hex()} {cases.SIGN().hex()}\n")
    sigs.close()
    os.environ["RV32RUN_SIGS"] = sigs.name
    rows, script_pool, elem_pool = [], bytearray(), bytearray()
    for name, (script, stack, _) in cases.hand().items():
        calls = []

        def h(b):
            calls.append("h")
            return hashlib.sha256(b).digest()

        def sig(pk, s):
            calls.append("s")
            return cases.valid(pk, s)

        want = script_verdict(script, stack, sig=sig, h=h)
        ran = model(rv32run, cases.region_image(kernel, script, stack), FUEL)[0]
        if not ran.startswith(f"halt code={want:08x} count="):
            sys.exit(f"gen.py: {name}: script.py says {want}, the model {ran}")
        count = int(ran.split("count=")[1].split()[0])
        rows.append((name, len(script_pool), len(script), len(stack), len(elem_pool), want, count + 4 + 4 * len(calls)))
        script_pool += script
        for e in stack:
            elem_pool += bytes([len(e)]) + e
    os.unlink(sigs.name)
    with open(out, "w") as f:
        f.write("// Generated by exp228/gen.py. Do not edit.\n#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define KERNEL_LEN {len(kernel)}\n#define NCASES {len(rows)}\n")
        f.write("static const uint8_t KERNEL[KERNEL_LEN] = {" + c_bytes(kernel) + "};\n")
        f.write("static const uint8_t KERNEL_SHA[32] = {" + c_bytes(bytes.fromhex(sha)) + "};\n")
        f.write("static const uint8_t MSG[32] = {" + c_bytes(cases.MSG) + "};\n")
        f.write("static const uint8_t SCRIPTS[] = {" + c_bytes(script_pool) + "};\n")
        f.write("static const uint8_t ELEMS[] = {" + c_bytes(elem_pool) + "};\n")
        f.write("struct kcase { const char *name; uint16_t script, script_len; uint8_t depth; uint16_t elems; "
                "uint8_t want; uint32_t instret; };\n")
        f.write("static const struct kcase CASES[NCASES] = {\n")
        for name, so, sl, d, eo, want, instret in rows:
            f.write(f'    {{"{name}", {so}, {sl}, {d}, {eo}, {want}, {instret}}},\n')
        f.write("};\n")
    print(f"{out}: kernel {sha[:16]}…, {len(rows)} cases, "
          f"{sum(1 for r in rows if r[5] == 0)} accepted, scripts {len(script_pool)} bytes, stacks {len(elem_pool)}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    header(sys.argv[1], sys.argv[2])
