"""
Writes proof/Equiv.lean.

The theorems here are about two binaries at once, exp240's monitor.bin and exp245's, so the file holds both proofs:
exp240's proof/Wx.lean, in namespace Exp240, and exp245's proof/Bless.lean, in namespace Exp245, as their own
generators write them and their own check.sh holds them -- read here, not written again -- with their `#print`
lines dropped; then tail.lean, the theorems that join them, in namespace Exp246, on lean/Rv32/WxTwin.lean.

  gen.py            write Equiv.lean
  gen.py --check    exit 0 if Equiv.lean is what this writes
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "../../.."))
OUT = os.path.join(HERE, os.environ.get("OUT", "Equiv.lean"))
EXP240 = os.path.join(REPO, "experiments", "exp240-the-code-the-box-forbids-writing", "proof", "Wx.lean")
EXP245 = os.path.join(REPO, "experiments", "exp245-the-bytes-the-proof-blesses", "proof", "Bless.lean")

HEAD = """/-
SPDX-License-Identifier: Apache-2.0

# exp246 — the run the charms do not change

exp240's monitor and exp245's, the same to a payload: one round under each, from machines whose boxes hold the same
bytes, is the same round -- the payload's steps, its first trap, what the host hears, the box at the park but for
exp245's slot -- and so are any number of rounds in which every exit leaves the slot zero.

GENERATED by gen.py: exp240's proof/Wx.lean (namespace Exp240) and exp245's proof/Bless.lean (namespace Exp245) as
their generators write them, then tail.lean (namespace Exp246).
-/
import Rv32.PrivRun
import Rv32.Refinement
import Rv32.Sandbox
import Rv32.WxBox
import Rv32.WxTwin

set_option linter.unusedSimpArgs false
set_option linter.unusedVariables false
"""


def body(path: str, ns: str) -> str:
    """A proof's namespace, from `namespace` to `end`, without the `#print` lines after it."""
    with open(path, encoding="utf-8") as f:
        t = f.read()
    i = t.index(f"namespace {ns}\n")
    j = t.index(f"end {ns}\n", i) + len(f"end {ns}\n")
    return t[i:j]


def read(name: str) -> str:
    with open(os.path.join(HERE, name), encoding="utf-8") as f:
        return f.read()


def build() -> str:
    return "\n".join([HEAD, body(EXP240, "Exp240"), body(EXP245, "Exp245"), read("tail.lean")])


def main():
    text = build()
    if "--check" in sys.argv:
        with open(OUT, encoding="utf-8") as g:
            return 0 if g.read() == text else 1
    with open(OUT, "w", encoding="utf-8") as g:
        g.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
