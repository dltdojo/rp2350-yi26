// One source, several versions — and deliberately **no slot letter**. The whole
// question here is whether a file can be built without knowing which half of an
// A/B pair it will end up in, so nothing in this build says.
//
// The version is emitted twice: as consts for the IMAGE_DEF's VERSION item, and
// as a `rustc-env` string so it can go into the USB product descriptor at
// compile time. `yi26 port` then names the running version without opening a
// log, which is what makes each drop's outcome readable in one call.
use std::{env, fs, path::PathBuf};

fn main() {
    let major: u16 = env::var("EXP145_MAJOR").ok().and_then(|v| v.parse().ok()).unwrap_or(1);
    let minor: u16 = env::var("EXP145_MINOR").ok().and_then(|v| v.parse().ok()).unwrap_or(0);

    let out = PathBuf::from(env::var_os("OUT_DIR").unwrap());
    let body = format!(
        "// generated by build.rs — do not edit\n\
         pub const VERSION_MAJOR: u16 = {major};\n\
         pub const VERSION_MINOR: u16 = {minor};\n"
    );
    fs::write(out.join("exp145_config.rs"), body).unwrap();

    println!("cargo:rustc-env=EXP145_VERSION={major}.{minor}");
    for var in ["EXP145_MAJOR", "EXP145_MINOR"] {
        println!("cargo:rerun-if-env-changed={var}");
    }
    println!("cargo:rerun-if-changed=build.rs");
}
