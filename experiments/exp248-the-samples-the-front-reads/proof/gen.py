"""
Writes proof/Front.lean.

exp223's proof/Condition.lean, in namespace Exp223, as exp223's own check.sh holds it -- read here, not written
again -- with its `#print` lines and its `main` dropped; then tail.lean, in namespace Exp248: exp223's front through
lean/Rv32/Reach.lean.

  gen.py            write Front.lean
  gen.py --check    exit 0 if Front.lean is what this writes
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "../../.."))
OUT = os.path.join(HERE, os.environ.get("OUT", "Front.lean"))
EXP223 = os.path.join(REPO, "experiments", "exp223-the-digest-the-kernel-withholds", "proof", "Condition.lean")

HEAD = """/-
SPDX-License-Identifier: Apache-2.0

# exp248 — the samples the front reads

exp223's front -- the health tests over the 1024 samples, and the branch to SHA-256 -- through the reach checker:
up to the branch, every load is of a sample, nothing is stored, and the only call is HALT.

GENERATED by gen.py: exp223's proof/Condition.lean (namespace Exp223) as its own check.sh holds it, then tail.lean
(namespace Exp248).
-/
import Rv32.Health
import Rv32.Within
import Rv32.Sha
import Rv32.Asm
import Rv32.Reach
"""


def read(path: str) -> str:
    with open(path, encoding="utf-8") as f:
        return f.read()


def condition() -> str:
    """exp223's proof from its `namespace` to its `end`, without the `#print` lines."""
    t = read(EXP223)
    t = t[t.index("namespace Exp223\n"):t.index("def main")]
    return "".join(line for line in t.splitlines(keepends=True) if not line.startswith("#print")).rstrip() + "\n"


def build() -> str:
    return "\n".join([HEAD, condition(), read(os.path.join(HERE, "tail.lean"))])


def main():
    text = build()
    if "--check" in sys.argv:
        with open(OUT, encoding="utf-8") as g:
            return 0 if g.read() == text else 1
    with open(OUT, "w", encoding="utf-8") as g:
        g.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
