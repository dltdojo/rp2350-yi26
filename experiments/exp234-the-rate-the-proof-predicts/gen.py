"""exp234 — what the shell compiles in, computed here.

  gen.py OUT.h RV32RUN

  KERNEL, KERNEL_SHA   kernel.bin, checked against kernel.sha256
  INSTRET              the Hazard3 RTL's minstret for the image, the count the
                       chip is asked to match on every run; the same for a
                       model run and a world run of different patients, since
                       the theorem's count depends on neither — after the Lean
                       model has run one patient's world at the chip's region
                       and halted with 0 after exactly 4043, leaving cure.py's
                       generations and nothing else
  DAYS … SEARCH_SEED   the trial's constants, exp232's cure.py's
  ANSWER, ACCEPTED, RELAPSING, LOOPHOLE
                       what cure.py's search finds, which the chip's must
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "tools", "hazard3", "shell"))
from expect import c_bytes, kernel_bin, model, rtl  # noqa: E402
from world import HIST_OFF, cure, history_bytes, world_image  # noqa: E402


def world_header(out, rv32run):
    kernel, sha = kernel_bin(os.path.join(HERE, "kernel"))
    answer, accepted, relapsing, loophole = cure.search()
    t = cure.lump(6)
    masks = cure.masks_of(0xd75dc8a3)
    img = world_image(kernel, t, ~t & cure.M, answer, masks)
    ran, region = model(rv32run, img, 5000)
    if ran != "halt code=00000000 count=4043":
        sys.exit(f"gen.py: the model did not halt with 0 after 4043: {ran}")
    want = bytearray(img) + bytearray(len(region) - len(img))
    want[HIST_OFF:HIST_OFF + 768] = history_bytes(t, ~t & cure.M, answer, masks)
    if region != bytes(want):
        sys.exit("gen.py: the model's region is not the image with cure.py's world")
    counts = set()
    t3 = cure.lump(3, 9)
    for args in ((t, ~t & cure.M, answer, masks), (t3, cure.M ^ t3, loophole, [0] * cure.GENS)):
        r = rtl(world_image(kernel, *args))
        if not r.startswith("halt code=00000000 instret="):
            sys.exit(f"gen.py: the RTL did not halt with 0: {r}")
        counts.add(int(r.split("instret=")[1].split()[0]))
    if len(counts) != 1:
        sys.exit(f"gen.py: the RTL counted differently for two patients: {counts}")
    instret = counts.pop()
    with open(out, "w") as f:
        f.write("// Generated by exp234/gen.py. Do not edit.\n#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define KERNEL_LEN {len(kernel)}\n")
        f.write(f"#define INSTRET {instret}u   // the RTL harness's minstret, whatever the patient and the masks\n")
        for name in ("DAYS", "DETECT", "TISSUE_MIN", "MUT_BITS", "CANDIDATES", "SEARCH_SEED"):
            f.write(f"#define {name} {getattr(cure, name)}u\n")
        f.write(f"#define WIDTH_MAX {max(cure.WIDTHS)}u\n")
        f.write(f"#define ANSWER {answer:#x}u\n#define ACCEPTED {accepted}u\n")
        f.write(f"#define RELAPSING {relapsing}u\n#define LOOPHOLE {loophole:#x}u\n")
        f.write("static const uint8_t KERNEL[KERNEL_LEN] = {" + c_bytes(kernel) + "};\n")
        f.write("static const uint8_t KERNEL_SHA[32] = {" + c_bytes(bytes.fromhex(sha)) + "};\n")
    print(f"{out}: kernel {sha[:16]}…, model 4043, RTL minstret {instret}, "
          f"search {accepted} accepted, {relapsing} relapsing, answer {answer:06x}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    world_header(sys.argv[1], sys.argv[2])
