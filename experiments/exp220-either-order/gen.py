"""exp220 — what the shell checks against, computed here and compiled in.

  gen.py OUT.h RV32RUN

As exp219's gen.py, for exp203's copy kernel and one fixed message, and:

  INVERT, REVERSE   the two PIO programs' words, read out of proof/Through.lean's
                    `words_invert` and `words_reverse` — theorems, so they are
                    what `encode` makes; INVERT is also checked to be exp217's
                    `prog`
  INVERTED          each of the 16 copied words, complemented
  REVERSED          each, bit-reversed
  ANSWERS           each, bit-reversed and complemented: what both orders
                    must give, by `either_order`

computed here in Python, not by the model, so the chip is held to a third
reading of what the two operations are.
"""
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
INVERT217 = os.path.join(HERE, "..", "exp217-the-words-the-model-inverts", "proof", "Invert.lean")
THROUGH = os.path.join(HERE, "proof", "Through.lean")
sys.path.insert(0, os.path.join(HERE, "..", "..", "tools", "hazard3", "shell"))
from copyrun import run_copy, write_copy  # noqa: E402

MESSAGE = b"exp220: Hazard3 copies. PIO0 inverts, PIO1 reverses, either way."


def lean_words(path, pattern):
    m = re.search(pattern + r"\[([^\]]*)\]", open(path).read(), re.M)
    if not m:
        sys.exit(f"gen.py: no {pattern} in {os.path.basename(path)}")
    return [int(t, 16) for t in m[1].split(",")]


def bit_reverse(w):
    return int(f"{w:032b}"[::-1], 2)


def write_two_blocks(out, rv32run):
    invert = lean_words(THROUGH, r"^theorem words_invert : prog \.invert = ")
    reverse = lean_words(THROUGH, r"^theorem words_reverse : prog \.reverse = ")
    if invert != lean_words(INVERT217, r"^def prog : List \(BitVec 16\) := "):
        sys.exit("gen.py: words_invert is not exp217's prog")
    run = run_copy(MESSAGE, rv32run)
    words = struct.unpack("<16I", MESSAGE)
    inverted = [~w & 0xffffffff for w in words]
    reversed_ = [bit_reverse(w) for w in words]
    answers = [~bit_reverse(w) & 0xffffffff for w in words]
    if [bit_reverse(v) for v in inverted] != answers:
        sys.exit("gen.py: Python's two orders disagree")
    u32 = lambda ws: ", ".join(f"0x{w:08x}u" for w in ws)
    u16 = lambda ws: ", ".join(f"0x{w:04x}" for w in ws)
    with open(out, "w") as f:
        f.write("// Generated by exp220/gen.py from exp203's sources and proof/Through.lean. Do not edit.\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        write_copy(f, run)
        f.write(f"// words_invert: {' '.join(f'{w:04x}' for w in invert)}   (PIO0)\n")
        f.write(f"// words_reverse: {' '.join(f'{w:04x}' for w in reverse)}   (PIO1)\n")
        f.write(f"#define PROGRAM_LEN 3\nstatic const uint16_t INVERT[3] = {{{u16(invert)}}};\n")
        f.write(f"static const uint16_t REVERSE[3] = {{{u16(reverse)}}};\n#define JMP_0 0x0000u\n\n")
        f.write(f"// {MESSAGE.decode()}\n// as 16 little-endian words: complemented, reversed, and both\n")
        f.write(f"static const uint32_t INVERTED[16] = {{{u32(inverted)}}};\n")
        f.write(f"static const uint32_t REVERSED[16] = {{{u32(reversed_)}}};\n")
        f.write(f"static const uint32_t ANSWERS[16] = {{{u32(answers)}}};\n")
    print(f"{out}: kernel {run['sha'][:16]}…, RTL minstret {run['instret']}, "
          f"PIO0 {' '.join(f'{w:04x}' for w in invert)}, PIO1 {' '.join(f'{w:04x}' for w in reverse)}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    write_two_blocks(sys.argv[1], sys.argv[2])
