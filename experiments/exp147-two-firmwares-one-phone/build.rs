// One source, two firmwares. Three build inputs, and the third is the one that
// matters here: the blink period, because it is what makes the ROM's choice
// visible to somebody holding a phone and no toolchain.
//
// A slot letter and a version are exp142's pattern. A blink rate is this
// experiment's whole point — an LED is the only instrument that needs nothing
// installed to read.
use std::{env, fs, path::PathBuf};

fn main() {
    let slot = env::var("EXP147_SLOT").unwrap_or_else(|_| "A".to_string());
    let major: u16 = env::var("EXP147_MAJOR").ok().and_then(|v| v.parse().ok()).unwrap_or(1);
    let minor: u16 = env::var("EXP147_MINOR").ok().and_then(|v| v.parse().ok()).unwrap_or(0);
    // Half a period, in milliseconds: the LED is on for this long and off for
    // this long. 100 is unmistakably fast, 1000 unmistakably slow, and nobody
    // has to time anything to tell them apart.
    let blink: u64 = env::var("EXP147_BLINK_MS").ok().and_then(|v| v.parse().ok()).unwrap_or(100);

    let pace = if blink <= 300 { "fast" } else { "slow" };

    let out = PathBuf::from(env::var_os("OUT_DIR").unwrap());
    let body = format!(
        "// generated by build.rs — do not edit\n\
         pub const SLOT: &str = {slot:?};\n\
         pub const VERSION_MAJOR: u16 = {major};\n\
         pub const VERSION_MINOR: u16 = {minor};\n\
         pub const BLINK_MS: u64 = {blink};\n\
         pub const PACE: &str = {pace:?};\n"
    );
    fs::write(out.join("exp147_config.rs"), body).unwrap();

    // Into the USB product descriptor, so `inspect.html` on a phone names the
    // running half without anyone opening a log.
    println!("cargo:rustc-env=EXP147_LABEL=slot {slot} {pace}");

    for var in ["EXP147_SLOT", "EXP147_MAJOR", "EXP147_MINOR", "EXP147_BLINK_MS"] {
        println!("cargo:rerun-if-env-changed={var}");
    }
    println!("cargo:rerun-if-changed=build.rs");
}
