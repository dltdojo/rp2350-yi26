"""exp209 — what the shell checks against, computed here and compiled in.

  gen.py OUT.h RV32RUN

Writes OUT.h from exp203's own sources and nothing typed by hand:

  IMAGE_OFFSET, IMAGE_DATA   exp203's `counting` image (its images.py), as the
                             64-byte blocks that are not all zero; the shell
                             zeroes the region and writes these
  KERNEL_LEN, KERNEL_SHA     kernel.bin's length, and kernel.sha256 — which is
                             checked here to be the hash of the image's first
                             KERNEL_LEN bytes before it is compiled in
  REGION_SHA                 SHA-256 of the whole 64 KiB region after the Lean
                             model (rv32run) runs the image at 0x20070000, where
                             the chip will; the model must halt with 0 after
                             exactly 105, the count exp203 proved
  SRC_OFF, DST_OFF           exp203's source and destination
"""
import hashlib
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
EXP203 = os.path.join(HERE, "..", "exp203-the-count-the-proof-promised")
sys.path.insert(0, EXP203)
sys.path.insert(0, os.path.join(HERE, "..", "..", "tools", "hazard3"))
import images as exp203  # noqa: E402
from sigfile import read_sig  # noqa: E402

CHIP_REGION, REGION_SIZE, DATA_SET = 0x20070000, 0x10000, "counting"


def c_bytes(b):
    return ", ".join(f"0x{x:02x}" for x in b)


def write_header(out, rv32run):
    image = exp203.copy_image(exp203.data_sets()[DATA_SET])
    kernel = open(os.path.join(EXP203, "kernel.bin"), "rb").read()
    want = open(os.path.join(EXP203, "kernel.sha256")).read().strip()
    if image[:len(kernel)] != kernel or hashlib.sha256(kernel).hexdigest() != want:
        sys.exit("gen.py: exp203's image does not start with the kernel.sha256 kernel")
    with tempfile.TemporaryDirectory() as work:
        img, sig = os.path.join(work, "image.bin"), os.path.join(work, "region.sig")
        open(img, "wb").write(image)
        ran = subprocess.run([rv32run, img, hex(CHIP_REGION), hex(REGION_SIZE), "1000", str(REGION_SIZE), sig],
                             capture_output=True, text=True).stdout.strip()
        if ran != "halt code=00000000 count=105":
            sys.exit(f"gen.py: the model did not halt with 0 after 105 at {CHIP_REGION:#x}: {ran}")
        region = read_sig(sig)[:REGION_SIZE]
    blocks = [o for o in range(0, len(image), 64) if any(image[o:o + 64])]
    with open(out, "w") as f:
        f.write("// Generated by exp209/gen.py from exp203's sources. Do not edit.\n#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define IMAGE_BLOCKS {len(blocks)}\n#define KERNEL_LEN {len(kernel)}\n")
        f.write(f"#define SRC_OFF {exp203.SRC:#x}\n#define DST_OFF {exp203.DST:#x}\n\n")
        f.write("static const uint16_t IMAGE_OFFSET[IMAGE_BLOCKS] = {" + ", ".join(hex(o) for o in blocks) + "};\n")
        f.write("static const uint8_t IMAGE_DATA[IMAGE_BLOCKS][64] = {\n")
        for o in blocks:
            f.write("    {" + c_bytes(image[o:o + 64].ljust(64, b"\0")) + "},\n")
        f.write("};\n\n")
        f.write("static const uint8_t KERNEL_SHA[32] = {" + c_bytes(bytes.fromhex(want)) + "};\n")
        f.write("// " + hashlib.sha256(region).hexdigest() + ": the region, as the model left it\n")
        f.write("static const uint8_t REGION_SHA[32] = {" + c_bytes(hashlib.sha256(region).digest()) + "};\n")
    print(f"{out}: {len(blocks)} image blocks, kernel {want[:16]}…, region {hashlib.sha256(region).hexdigest()[:16]}…")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    write_header(sys.argv[1], sys.argv[2])
