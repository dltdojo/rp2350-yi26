// User presence is a build input, and both settings are honest.
//
// A FIDO2 authenticator must ask a person before it makes a credential, and
// says whether it did in one bit of the authenticator data. This device can do
// that -- the BOOTSEL button is exp106's -- but a run that needs a finger is a
// run that stops overnight, and this repository tracks that as a cost.
//
// So `none` builds a device that sets the bit to zero and says so, which any
// client will refuse and `check.sh` can drive unattended; `button` builds one
// that waits for a press and sets the bit truthfully. Neither lies.
use std::{env, fs, path::PathBuf};

fn main() {
    let up = env::var("EXP173_UP").unwrap_or_else(|_| "none".to_string());
    let waits = match up.as_str() {
        "none" => false,
        "button" => true,
        other => panic!("EXP173_UP must be `none` or `button`, not `{other}`"),
    };
    let out = PathBuf::from(env::var_os("OUT_DIR").unwrap());
    fs::write(
        out.join("exp173_config.rs"),
        format!(
            "// generated by build.rs — do not edit\n\
             pub const UP_MODE: &str = {up:?};\n\
             /// Does this build wait for a person before making a credential?\n\
             pub const WAIT_FOR_USER: bool = {waits};\n"
        ),
    )
    .unwrap();
    println!("cargo:rerun-if-env-changed=EXP173_UP");
    println!("cargo:rerun-if-changed=build.rs");
}
