"""
Writes proof/Wall.lean.

The theorem here is about four proofs at once, so the file holds them all, each as its own check holds it -- read
here, not written again:

  exp223's proof/Condition.lean   namespace Exp223   the kernel, and what its run ends with
  exp248's proof/tail.lean        namespace Exp248   its front, every step, up to SHA-256
  exp249's proof/Hash.lean        namespace Exp249   its SHA-256, every step
  exp239's proof/Scrub.lean       namespace Exp239   the monitor, from reset and from the trap vector

with their `#print` lines and exp223's `main` dropped; then tail.lean, in namespace Exp250, with
tools/monitor/boot_ports.lean spliced in where it says so.

  gen.py            write Wall.lean
  gen.py --check    exit 0 if Wall.lean is what this writes
"""
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "../../.."))
OUT = os.path.join(HERE, os.environ.get("OUT", "Wall.lean"))
EXP = os.path.join(REPO, "experiments")
EXP248_GEN = os.path.join(EXP, "exp248-the-samples-the-front-reads", "proof", "gen.py")
EXP248_TAIL = os.path.join(EXP, "exp248-the-samples-the-front-reads", "proof", "tail.lean")
EXP249 = os.path.join(EXP, "exp249-the-words-the-hash-touches", "proof", "Hash.lean")
EXP239 = os.path.join(EXP, "exp239-the-scratch-the-monitor-scrubs", "proof", "Scrub.lean")
PORTS = os.path.join(REPO, "tools", "monitor", "boot_ports.lean")

HEAD = """/-
SPDX-License-Identifier: Apache-2.0

# exp250 — the digest the wall keeps

exp223's kernel -- the health tests, then SHA-256 -- run as exp239's payload: from reset, the monitor boots, the
kernel runs in the box and HALTs, and the monitor parks with the digest kept or the scratch scrubbed, the host
having heard exactly the HALT report and the exit code.

GENERATED by gen.py: exp223's proof/Condition.lean (Exp223), exp248's proof/tail.lean (Exp248), exp249's
proof/Hash.lean (Exp249) and exp239's proof/Scrub.lean (Exp239), each as its own check holds it, then tail.lean
(Exp250) with tools/monitor/boot_ports.lean spliced in.
-/
import Rv32.Health
import Rv32.Within
import Rv32.Sha
import Rv32.Asm
import Rv32.Reach
import Rv32.PrivRun
import Rv32.Refinement
import Rv32.Sandbox
import Rv32.Join
"""


def read(path: str) -> str:
    with open(path, encoding="utf-8") as f:
        return f.read()


def gen248():
    spec = importlib.util.spec_from_file_location("gen248", EXP248_GEN)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def body(path: str, ns: str, opts: str = "") -> str:
    """A proof's namespace, from `namespace` to `end`, without the `#print` lines."""
    t = read(path)
    i = t.index(f"namespace {ns}\n")
    j = t.index(f"end {ns}\n", i) + len(f"end {ns}\n")
    return opts + "".join(line for line in t[i:j].splitlines(keepends=True) if not line.startswith("#print"))


def ports() -> str:
    t = read(PORTS)
    return t[t.index("-/\n") + 3:].lstrip("\n")


def build() -> str:
    tail = read(os.path.join(HERE, "tail.lean")).replace("-- SPLICE: tools/monitor/boot_ports.lean\n\n", ports())
    lint = "set_option linter.unusedSimpArgs false\nset_option linter.unusedVariables false\n\n"
    return "\n".join([HEAD, gen248().condition(), body(EXP248_TAIL, "Exp248"), body(EXP249, "Exp249"),
                      body(EXP239, "Exp239", lint), tail])


def main():
    text = build()
    if "--check" in sys.argv:
        with open(OUT, encoding="utf-8") as g:
            return 0 if g.read() == text else 1
    with open(OUT, "w", encoding="utf-8") as g:
        g.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
