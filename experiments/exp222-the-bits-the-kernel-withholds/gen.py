"""exp222 — what the shell checks against, computed here and compiled in.

  gen.py OUT.h RV32RUN

  KERNEL, KERNEL_SHA      kernel.bin, as proof/Health.lean writes it, checked
                          against kernel.sha256
  INSTRET_PASS/_FAIL      the Hazard3 RTL's minstret for the kernel on a stream
                          that passes and on one that does not. By
                          `withholds` the count depends on the verdict alone,
                          so one of each is the count for every stream

and, before writing anything, the Lean model on the same two images: it must
halt with 0 after exactly 23574 on the first and with 1 after exactly 17427
on the second, the counts `withholds` proves.
"""
import os
import random
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "tools", "hazard3", "shell"))
sys.path.insert(0, os.path.join(HERE, "differential"))
from expect import c_bytes, kernel_bin, model, rtl  # noqa: E402
from streams import healthy  # noqa: E402

SAMPLES, N = 0x1000, 1024


def image(kernel, words):
    img = bytearray(0x10000)
    img[:len(kernel)] = kernel
    img[SAMPLES:SAMPLES + 4 * N] = struct.pack(f"<{N}I", *words)
    return bytes(img)


def write_health(out, rv32run):
    kernel, sha = kernel_bin(os.path.join(HERE, "kernel"))
    r = random.Random(222)
    good = [r.getrandbits(1) for _ in range(N)]
    if not healthy(good)[0]:
        sys.exit("gen.py: the passing stream does not pass")
    counts = {}
    for name, words, code, count in (("pass", good, 0, 23574), ("fail", [1] * N, 1, 17427)):
        img = image(kernel, words)
        ran, _ = model(rv32run, img, 30000)
        if ran != f"halt code={code:08x} count={count}":
            sys.exit(f"gen.py: on the {name} stream the model said {ran}")
        ran = rtl(img)
        if not ran.startswith(f"halt code={code:08x} instret="):
            sys.exit(f"gen.py: on the {name} stream the RTL said {ran}")
        counts[name] = int(ran.split("instret=")[1].split()[0])
    with open(out, "w") as f:
        f.write("// Generated by exp222/gen.py. Do not edit.\n#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define KERNEL_LEN {len(kernel)}\n")
        f.write(f"#define INSTRET_PASS {counts['pass']}u   // the RTL's minstret, HALT 0\n")
        f.write(f"#define INSTRET_FAIL {counts['fail']}u   // and HALT 1\n")
        f.write("static const uint8_t KERNEL[KERNEL_LEN] = {" + c_bytes(kernel) + "};\n")
        f.write("static const uint8_t KERNEL_SHA[32] = {" + c_bytes(bytes.fromhex(sha)) + "};\n")
    print(f"{out}: kernel {sha[:16]}…, RTL minstret {counts['pass']} healthy, {counts['fail']} withheld")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    write_health(sys.argv[1], sys.argv[2])
