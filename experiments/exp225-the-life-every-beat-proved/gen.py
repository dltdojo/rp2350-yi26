"""exp225 — what the shell compiles in, computed here.

  gen.py OUT.h RV32RUN

  KERNEL, KERNEL_SHA   kernel.bin, checked against kernel.sha256
  SEED0                the first life's seed: one live cell, bit 16
  HIST_SHA             SHA-256 of the 1024 bytes of its 256 generations, from
                       rule30.py — after the Lean model, running the image at
                       the chip's region, has halted with 0 after exactly
                       3079 and left exactly those bytes and nothing else
  INSTRET              the Hazard3 RTL's minstret for the image, the count
                       the chip is asked to match; the same for a second seed,
                       since the theorem's count does not depend on it
"""
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "tools", "hazard3", "shell"))
from expect import c_bytes, kernel_bin, model, rtl  # noqa: E402
from rule30 import HIST_OFF, SEED0, history_bytes, image  # noqa: E402


def write_header(out, rv32run):
    kernel, sha = kernel_bin(os.path.join(HERE, "kernel"))
    img = image(kernel, SEED0)
    ran, region = model(rv32run, img, 4000)
    if ran != "halt code=00000000 count=3079":
        sys.exit(f"gen.py: the model did not halt with 0 after 3079: {ran}")
    want = bytearray(img) + bytearray(len(region) - len(img))
    want[HIST_OFF:HIST_OFF + 1024] = history_bytes(SEED0)
    if region != bytes(want):
        sys.exit("gen.py: the model's region is not the image with rule30.py's history")
    counts = set()
    for seed in (SEED0, 0xdeadbeef):
        r = rtl(image(kernel, seed))
        if not r.startswith("halt code=00000000 instret="):
            sys.exit(f"gen.py: the RTL did not halt with 0 for seed {seed:#x}: {r}")
        counts.add(int(r.split("instret=")[1].split()[0]))
    if len(counts) != 1:
        sys.exit(f"gen.py: the RTL counted differently for two seeds: {counts}")
    instret = counts.pop()
    hist_sha = hashlib.sha256(history_bytes(SEED0)).digest()
    with open(out, "w") as f:
        f.write("// Generated by exp225/gen.py. Do not edit.\n#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define KERNEL_LEN {len(kernel)}\n#define SEED0 {SEED0:#x}u\n")
        f.write(f"#define INSTRET {instret}u   // the RTL harness's minstret, whatever the seed\n")
        f.write("static const uint8_t KERNEL[KERNEL_LEN] = {" + c_bytes(kernel) + "};\n")
        f.write("static const uint8_t KERNEL_SHA[32] = {" + c_bytes(bytes.fromhex(sha)) + "};\n")
        f.write("static const uint8_t HIST_SHA[32] = {" + c_bytes(hist_sha) + "};\n")
    print(f"{out}: kernel {sha[:16]}…, model 3079, RTL minstret {instret}, first life {hist_sha.hex()[:16]}…")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    write_header(sys.argv[1], sys.argv[2])
