"""
Writes proof/Wall.lean.

The theorem here is about two proofs at once, exp229's kernel and exp236's monitor, so the file holds both:
exp229's proof/Field.lean, in namespace Exp229, and exp236's proof/Monitor.lean, in namespace Exp236, as their own
check.sh holds them -- read here, not written again -- with their `#print` lines and exp229's `main` dropped; then
tail.lean, the theorems that join them, in namespace Exp247, on lean/Rv32/Join.lean, with
tools/monitor/boot_ports.lean spliced in where it says so.

  gen.py            write Wall.lean
  gen.py --check    exit 0 if Wall.lean is what this writes
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "../../.."))
OUT = os.path.join(HERE, os.environ.get("OUT", "Wall.lean"))
EXP229 = os.path.join(REPO, "experiments", "exp229-the-remainder-the-kernel-keeps", "proof", "Field.lean")
EXP236 = os.path.join(REPO, "experiments", "exp236-the-wall-the-monitor-holds", "proof", "Monitor.lean")

HEAD = """/-
SPDX-License-Identifier: Apache-2.0

# exp247 — the remainder behind the wall

exp229's kernel, run as exp236's payload: from reset, the monitor boots, the kernel computes the field in the box
and HALTs, and the monitor parks -- with R holding the remainder when the kernel traps, and the host having heard
exactly the HALT report, its counts and the exit code 0.

GENERATED by gen.py: exp229's proof/Field.lean (namespace Exp229) and exp236's proof/Monitor.lean (namespace
Exp236) as their own check.sh holds them, then tail.lean (namespace Exp247).
-/
import Rv32.Blocks
import Rv32.Flow
import Rv32.Line
import Rv32.Limbs
import Rv32.Asm
import Rv32.PrivRun
import Rv32.Refinement
import Rv32.Sandbox
import Rv32.Join
"""


def read(path: str) -> str:
    with open(path, encoding="utf-8") as f:
        return f.read()


def field() -> str:
    """exp229's proof from its first `namespace` to its `main`, without the `#print` lines."""
    t = read(EXP229)
    t = t[t.index("namespace Exp229\n"):t.index("def main")]
    return "".join(line for line in t.splitlines(keepends=True) if not line.startswith("#print")).rstrip() + "\n"


def monitor() -> str:
    """exp236's proof from its `namespace` to its `end`, with the options it is checked under."""
    t = read(EXP236)
    i = t.index("namespace Exp236\n")
    j = t.index("end Exp236\n", i) + len("end Exp236\n")
    opts = "set_option linter.unusedSimpArgs false\nset_option linter.unusedVariables false\n\n"
    return opts + t[i:j]


PORTS = os.path.join(REPO, "tools", "monitor", "boot_ports.lean")


def ports() -> str:
    """tools/monitor/boot_ports.lean without its header: boot is silent, for a monitor whose boot is exp236's."""
    t = read(PORTS)
    return t[t.index("-/\n") + 3:].lstrip("\n")


def build() -> str:
    tail = read(os.path.join(HERE, "tail.lean")).replace("-- SPLICE: tools/monitor/boot_ports.lean\n\n", ports())
    return "\n".join([HEAD, field(), monitor(), tail])


def main():
    text = build()
    if "--check" in sys.argv:
        with open(OUT, encoding="utf-8") as g:
            return 0 if g.read() == text else 1
    with open(OUT, "w", encoding="utf-8") as g:
        g.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
