"""exp231 — what the shell compiles in for the fly, computed here. The life's
half is exp225's gen.py, unchanged, into expect.h.

  gen.py OUT.h RV32RUN

  FLY, FLY_SHA         exp230's kernel.bin, checked against its kernel.sha256
  FLY_STEPS_SHA        SHA-256 of the 2048 bytes of the first round's 256
  FLY_UP0, FLY_DOWN0   steps, and its two totals, from fly.py — after the Lean
                       model, running the image at the chip's region, has
                       halted with 0 after exactly 70924 and left exactly those
  FLY_INSTRET          the Hazard3 RTL's minstret for the image, the count the
                       chip is asked to match; the same for frames of noise,
                       since the theorem's count does not depend on them
"""
import hashlib
import os
import random
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FLY_DIR = os.path.join(HERE, "..", "exp230-the-motion-the-fly-sees")
sys.path.insert(0, os.path.join(HERE, "..", "..", "tools", "hazard3", "shell"))
sys.path.insert(0, FLY_DIR)
from expect import c_bytes, kernel_bin, model, rtl  # noqa: E402
from fly import DOWN, N, STEPS, UP, chain, fly_image, fly_ref  # noqa: E402
from rule30 import SEED0, rule30  # noqa: E402


def first_frames():
    """What the fly watches in round 0: the seed, then the life grown from it."""
    return chain(SEED0, rule30)


def steps_bytes(steps):
    return b"".join(struct.pack("<II", u, d) for u, d in steps)


def fly_header(out, rv32run):
    kernel, sha = kernel_bin(os.path.join(FLY_DIR, "kernel"))
    frames = first_frames()
    steps, up, down = fly_ref(frames)
    img = fly_image(kernel, frames)
    ran, region = model(rv32run, img, 100000)
    if ran != "halt code=00000000 count=70924":
        sys.exit(f"gen.py: the model did not halt with 0 after 70924: {ran}")
    want = bytearray(img) + bytearray(len(region) - len(img))
    want[STEPS:STEPS + 8 * N] = steps_bytes(steps)
    want[UP:UP + 4] = struct.pack("<I", up)
    want[DOWN:DOWN + 4] = struct.pack("<I", down)
    if region != bytes(want):
        sys.exit("gen.py: the model's region is not the image with fly.py's steps and totals")
    counts = set()
    noise = random.Random(231)
    for f in (frames, [noise.getrandbits(32) for _ in range(N + 1)]):
        r = rtl(fly_image(kernel, f))
        if not r.startswith("halt code=00000000 instret="):
            sys.exit(f"gen.py: the RTL did not halt with 0: {r}")
        counts.add(int(r.split("instret=")[1].split()[0]))
    if len(counts) != 1:
        sys.exit(f"gen.py: the RTL counted differently for two sets of frames: {counts}")
    instret = counts.pop()
    steps_sha = hashlib.sha256(steps_bytes(steps)).digest()
    with open(out, "w") as f:
        f.write("// Generated by exp231/gen.py. Do not edit.\n#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define FLY_LEN {len(kernel)}\n")
        f.write(f"#define FLY_INSTRET {instret}u   // the RTL harness's minstret, whatever the frames\n")
        f.write(f"#define FLY_UP0 {up}u\n#define FLY_DOWN0 {down}u\n")
        f.write("static const uint8_t FLY[FLY_LEN] = {" + c_bytes(kernel) + "};\n")
        f.write("static const uint8_t FLY_SHA[32] = {" + c_bytes(bytes.fromhex(sha)) + "};\n")
        f.write("static const uint8_t FLY_STEPS_SHA[32] = {" + c_bytes(steps_sha) + "};\n")
    print(f"{out}: fly {sha[:16]}…, model 70924, RTL minstret {instret}, "
          f"first round up {up} down {down}, steps {steps_sha.hex()[:16]}…")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    fly_header(sys.argv[1], sys.argv[2])
