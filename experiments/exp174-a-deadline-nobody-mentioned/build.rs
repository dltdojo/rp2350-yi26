// Two build inputs, and the second one is this experiment's whole subject.
//
// `EXP174_UP` is exp173's, unchanged: `none` builds a device that never asks
// and says so, `button` builds one that waits for a press. The `none` build is
// what lets `check.sh` run unattended; only the `button` build can be the
// subject here, because a device that never waits is never silent.
//
// `EXP174_KEEPALIVE` is the new one. While the `button` build waits for a
// finger it sends nothing, and a browser measured against that firmware gave up
// somewhere between 4.5 and 9.9 seconds -- then re-sent the same request on a
// fresh channel. `CTAPHID_KEEPALIVE` is the packet whose only job is to say
// "still here"; `off` and `on` are the same code with that packet suppressed,
// so the two arms differ by one thing and the difference is measurable.
use std::{env, fs, path::PathBuf};

fn flag(name: &str, default: bool) -> bool {
    match env::var(name) {
        Ok(v) => matches!(v.as_str(), "on" | "1" | "true" | "yes"),
        Err(_) => default,
    }
}

fn main() {
    let up = env::var("EXP174_UP").unwrap_or_else(|_| "none".to_string());
    let waits = match up.as_str() {
        "none" => false,
        "button" => true,
        other => panic!("EXP174_UP must be `none` or `button`, not `{other}`"),
    };
    // Default on. exp173 is the `off` arm already, and a build that quietly
    // reproduces the fault is not the one anybody should get by accident.
    let keepalive = flag("EXP174_KEEPALIVE", true);
    // A floor under the wait, and the reason it exists is that the first
    // attempt at this measurement asked a person to count to nine and a half
    // against a ten-second window. That is not an instrument. With a floor the
    // button is held down from the start and the *board* decides when the
    // answer leaves, so the number in the transcript is a clock's and not a
    // reflex's. Zero is the honest default and every earlier run used it.
    let hold: u64 = env::var("EXP174_HOLD_MS").ok().and_then(|v| v.parse().ok()).unwrap_or(0);
    // Ten seconds is what exp171 chose for a person who is not there. A floor
    // past it would be a build no press could satisfy, so the window is a
    // build input too -- and raising it is how the host's own ceiling gets
    // measured rather than guessed at.
    let timeout: u64 = env::var("EXP174_TIMEOUT_MS").ok().and_then(|v| v.parse().ok()).unwrap_or(10_000);
    let out = PathBuf::from(env::var_os("OUT_DIR").unwrap());
    fs::write(
        out.join("exp174_config.rs"),
        format!(
            "// generated by build.rs — do not edit\n\
             pub const UP_MODE: &str = {up:?};\n\
             /// Does this build wait for a person before making a credential?\n\
             pub const WAIT_FOR_USER: bool = {waits};\n\
             /// Does it say \"still here\" while it waits?\n\
             pub const KEEPALIVE: bool = {keepalive};\n\
             /// Refuse to answer before this many ms, even with the button held.\n\
             pub const HOLD_MS: u64 = {hold};\n\
             /// How long a person who is not there has, in ms.\n\
             pub const TIMEOUT_MS: u64 = {timeout};\n"
        ),
    )
    .unwrap();
    for var in ["EXP174_UP", "EXP174_KEEPALIVE", "EXP174_HOLD_MS", "EXP174_TIMEOUT_MS"] {
        println!("cargo:rerun-if-env-changed={var}");
    }
    println!("cargo:rerun-if-changed=build.rs");
}
