"""
Writes proof/Cells.lean.

exp225's proof/Life.lean, in namespace Exp225, as exp225's own check.sh holds it -- read here, not written
again -- with its `#print` lines and its `main` dropped; then tail.lean, in namespace Exp253: exp225's Rule 30 kernel
through lean/Rv32/Reach.lean.

  gen.py            write Cells.lean
  gen.py --check    exit 0 if Cells.lean is what this writes
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "../../.."))
OUT = os.path.join(HERE, os.environ.get("OUT", "Cells.lean"))
EXP225 = os.path.join(REPO, "experiments", "exp225-the-life-every-beat-proved", "proof", "Life.lean")

HEAD = """/-
SPDX-License-Identifier: Apache-2.0

# exp253 — the cells the kernel touches

exp225's Rule 30 kernel through the reach checker: every fetch one of its 19 instructions, every load the seed,
every store a cell of the history, the only call HALT.

GENERATED by gen.py: exp225's proof/Life.lean (namespace Exp225) as its own check.sh holds it, then tail.lean
(namespace Exp253).
-/
import Rv32.Blocks
import Rv32.Line
import Rv32.Asm
import Rv32.Reach
"""


def read(path: str) -> str:
    with open(path, encoding="utf-8") as f:
        return f.read()


def life() -> str:
    """exp225's proof from its `namespace` to its `end`, without the `#print` lines."""
    t = read(EXP225)
    t = t[t.index("namespace Exp225\n"):t.index("def main")]
    return "".join(line for line in t.splitlines(keepends=True) if not line.startswith("#print")).rstrip() + "\n"


def build() -> str:
    return "\n".join([HEAD, life(), read(os.path.join(HERE, "tail.lean"))])


def main():
    text = build()
    if "--check" in sys.argv:
        with open(OUT, encoding="utf-8") as g:
            return 0 if g.read() == text else 1
    with open(OUT, "w", encoding="utf-8") as g:
        g.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
