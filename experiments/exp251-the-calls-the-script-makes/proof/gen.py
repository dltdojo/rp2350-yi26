"""
Writes proof/Calls.lean.

exp228's proof/Script.lean, in namespace Exp228, as exp228's own check.sh holds it -- read here, not written
again -- with its `#print` lines and what follows them (its `main`, run by the shell's build) dropped; then
tail.lean, in namespace Exp251: the calls that kernel's run makes, in a world that does not serve HASH.

  gen.py            write Calls.lean
  gen.py --check    exit 0 if Calls.lean is what this writes
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "../../.."))
OUT = os.path.join(HERE, os.environ.get("OUT", "Calls.lean"))
EXP228 = os.path.join(REPO, "experiments", "exp228-the-script-the-kernel-runs", "proof", "Script.lean")

HEAD = """/-
SPDX-License-Identifier: Apache-2.0

# exp251 — the calls the script makes

exp228's kernel, in a world whose shell does not serve HASH (`t0 = 0`): it halts with the specification's
verdict, as exp228 proved for every world, and every call on the way is HALT, HASHB or CHECKSIG with its ranges
in the box -- the three calls exp238's monitor serves.

GENERATED by gen.py: exp228's proof/Script.lean (namespace Exp228) as its own check.sh holds it, then tail.lean
(namespace Exp251).
-/
import Rv32.Blocks
import Rv32.Flow
import Rv32.Line
import Rv32.Asm
import Rv32.Join
"""


def read(path: str) -> str:
    with open(path, encoding="utf-8") as f:
        return f.read()


def script() -> str:
    """exp228's proof from its first `namespace` to its first `#print`."""
    t = read(EXP228)
    t = t[t.index("namespace Exp228\n"):t.index("#print axioms")]
    return t.rstrip() + "\n"


def build() -> str:
    return "\n".join([HEAD, script(), read(os.path.join(HERE, "tail.lean"))])


def main():
    text = build()
    if "--check" in sys.argv:
        with open(OUT, encoding="utf-8") as g:
            return 0 if g.read() == text else 1
    with open(OUT, "w", encoding="utf-8") as g:
        g.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
