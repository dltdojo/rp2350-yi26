"""exp219 — what the shell checks against, computed here and compiled in.

  gen.py OUT.h RV32RUN

Writes OUT.h from two experiments' sources and one fixed message, nothing
else typed by hand:

  IMAGE_OFFSET, IMAGE_DATA   exp203's image (its images.py) with MESSAGE as
                             the 64 source bytes, as the 64-byte blocks that
                             are not all zero
  KERNEL_LEN, KERNEL_SHA     kernel.bin's length and kernel.sha256, checked
                             here to be the hash of the image's first bytes
  REGION_SHA                 the whole 64 KiB region after the Lean model
                             (rv32run) runs the image where the chip will;
                             the model must halt with 0 after exactly 105,
                             the count exp203 proved
  SRC_OFF, DST_OFF           exp203's source and destination
  EXPECT_INSTRET             the Hazard3 RTL's minstret for the same image
  PROGRAM                    the PIO words exp217's theorems are about,
                             read out of its proof/Invert.lean
  ANSWERS                    what RX must give back: each of the 16 words
                             the kernel copied, complemented. Two theorems
                             say so together: exp203's `copies` (the
                             destination holds the source) and exp217's
                             `every_word` (RX holds TX, complemented, in
                             order)
"""
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
INVERT = os.path.join(HERE, "..", "exp217-the-words-the-model-inverts", "proof", "Invert.lean")
sys.path.insert(0, os.path.join(HERE, "..", "..", "tools", "hazard3", "shell"))
from copyrun import run_copy, write_copy  # noqa: E402

MESSAGE = b"exp219: Hazard3 copies these 64 bytes, then PIO0 inverts all 16."


def pio_words():
    m = re.search(r"^def prog : List \(BitVec 16\) := \[([^\]]*)\]$", open(INVERT).read(), re.M)
    if not m:
        sys.exit("gen.py: no `def prog` in exp217's Invert.lean")
    return [int(t, 16) for t in m[1].split(",")]


def write_expect(out, rv32run):
    run = run_copy(MESSAGE, rv32run)
    answers = [~w & 0xffffffff for w in struct.unpack("<16I", MESSAGE)]
    prog = pio_words()
    with open(out, "w") as f:
        f.write("// Generated by exp219/gen.py from exp203's and exp217's sources. Do not edit.\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        write_copy(f, run)
        f.write(f"// exp217's `prog`: {' '.join(f'{w:04x}' for w in prog)}\n")
        f.write(f"#define PROGRAM_LEN {len(prog)}\n")
        f.write("static const uint16_t PROGRAM[PROGRAM_LEN] = {" + ", ".join(f"0x{w:04x}" for w in prog) + "};\n")
        f.write("#define JMP_0 0x0000u\n\n")
        f.write(f"// {MESSAGE.decode()}\n// as 16 little-endian words, each complemented\n")
        f.write("static const uint32_t ANSWERS[16] = {" + ", ".join(f"0x{a:08x}u" for a in answers) + "};\n")
    print(f"{out}: kernel {run['sha'][:16]}…, RTL minstret {run['instret']}, PIO words {' '.join(f'{w:04x}' for w in prog)}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    write_expect(sys.argv[1], sys.argv[2])
