"""exp219 — what the shell checks against, computed here and compiled in.

  gen.py OUT.h RV32RUN

Writes OUT.h from two experiments' sources and one fixed message, nothing
else typed by hand:

  IMAGE_OFFSET, IMAGE_DATA   exp203's image (its images.py) with MESSAGE as
                             the 64 source bytes, as the 64-byte blocks that
                             are not all zero
  KERNEL_LEN, KERNEL_SHA     kernel.bin's length and kernel.sha256, checked
                             here to be the hash of the image's first bytes
  REGION_SHA                 the whole 64 KiB region after the Lean model
                             (rv32run) runs the image where the chip will;
                             the model must halt with 0 after exactly 105,
                             the count exp203 proved
  SRC_OFF, DST_OFF           exp203's source and destination
  EXPECT_INSTRET             the Hazard3 RTL's minstret for the same image
  PROGRAM                    the PIO words exp217's theorems are about,
                             read out of its proof/Invert.lean
  ANSWERS                    what RX must give back: each of the 16 words
                             the kernel copied, complemented. Two theorems
                             say so together: exp203's `copies` (the
                             destination holds the source) and exp217's
                             `every_word` (RX holds TX, complemented, in
                             order)
"""
import hashlib
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXP203 = os.path.join(HERE, "..", "exp203-the-count-the-proof-promised")
INVERT = os.path.join(HERE, "..", "exp217-the-words-the-model-inverts", "proof", "Invert.lean")
sys.path.insert(0, EXP203)
sys.path.insert(0, os.path.join(HERE, "..", "..", "tools", "hazard3", "shell"))
import images as exp203  # noqa: E402
from expect import CHIP_REGION, c_bytes, model, rtl  # noqa: E402

MESSAGE = b"exp219: Hazard3 copies these 64 bytes, then PIO0 inverts all 16."


def pio_words():
    m = re.search(r"^def prog : List \(BitVec 16\) := \[([^\]]*)\]$", open(INVERT).read(), re.M)
    if not m:
        sys.exit("gen.py: no `def prog` in exp217's Invert.lean")
    return [int(t, 16) for t in m[1].split(",")]


def write_expect(out, rv32run):
    if len(MESSAGE) != 64:
        sys.exit("gen.py: the message must be 64 bytes")
    image = exp203.copy_image(MESSAGE)
    kernel = open(os.path.join(EXP203, "kernel.bin"), "rb").read()
    want = open(os.path.join(EXP203, "kernel.sha256")).read().strip()
    if image[:len(kernel)] != kernel or hashlib.sha256(kernel).hexdigest() != want:
        sys.exit("gen.py: exp203's image does not start with the kernel.sha256 kernel")
    ran, region = model(rv32run, image, 1000)
    if ran != "halt code=00000000 count=105":
        sys.exit(f"gen.py: the model did not halt with 0 after 105 at {CHIP_REGION:#x}: {ran}")
    if region[exp203.DST:exp203.DST + 64] != MESSAGE:
        sys.exit("gen.py: the model's destination is not the message")
    ran = rtl(image)
    if not ran.startswith("halt code=00000000 instret="):
        sys.exit(f"gen.py: the RTL did not halt with 0: {ran}")
    instret = int(ran.split("instret=")[1].split()[0])
    answers = [~w & 0xffffffff for w in struct.unpack("<16I", MESSAGE)]
    prog = pio_words()
    blocks = [o for o in range(0, len(image), 64) if any(image[o:o + 64])]
    with open(out, "w") as f:
        f.write("// Generated by exp219/gen.py from exp203's and exp217's sources. Do not edit.\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define IMAGE_BLOCKS {len(blocks)}\n#define KERNEL_LEN {len(kernel)}\n")
        f.write(f"#define SRC_OFF {exp203.SRC:#x}\n#define DST_OFF {exp203.DST:#x}\n")
        f.write(f"#define EXPECT_INSTRET {instret}u   // the RTL harness's minstret for this image\n\n")
        f.write("static const uint16_t IMAGE_OFFSET[IMAGE_BLOCKS] = {" + ", ".join(hex(o) for o in blocks) + "};\n")
        f.write("static const uint8_t IMAGE_DATA[IMAGE_BLOCKS][64] = {\n")
        for o in blocks:
            f.write("    {" + c_bytes(image[o:o + 64].ljust(64, b"\0")) + "},\n")
        f.write("};\n\n")
        f.write("static const uint8_t KERNEL_SHA[32] = {" + c_bytes(bytes.fromhex(want)) + "};\n")
        f.write("// " + hashlib.sha256(region).hexdigest() + ": the region, as the model left it\n")
        f.write("static const uint8_t REGION_SHA[32] = {" + c_bytes(hashlib.sha256(region).digest()) + "};\n\n")
        f.write(f"// exp217's `prog`: {' '.join(f'{w:04x}' for w in prog)}\n")
        f.write(f"#define PROGRAM_LEN {len(prog)}\n")
        f.write("static const uint16_t PROGRAM[PROGRAM_LEN] = {" + ", ".join(f"0x{w:04x}" for w in prog) + "};\n")
        f.write("#define JMP_0 0x0000u\n\n")
        f.write(f"// {MESSAGE.decode()}\n// as 16 little-endian words, each complemented\n")
        f.write("static const uint32_t ANSWERS[16] = {" + ", ".join(f"0x{a:08x}u" for a in answers) + "};\n")
    print(f"{out}: kernel {want[:16]}…, region {hashlib.sha256(region).hexdigest()[:16]}…, "
          f"RTL minstret {instret}, PIO words {' '.join(f'{w:04x}' for w in prog)}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    write_expect(sys.argv[1], sys.argv[2])
